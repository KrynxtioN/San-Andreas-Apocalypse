local posX, targetPosX, speed, selectedIndex, offset = -300, 10, 10, 1, 0
local entries = {}
local x,y = guiGetScreenSize()

function Radio.dxDraw()
    if(posX < targetPosX)then
        posX = posX + speed
        if(posX > targetPosX)then posX = targetPosX end
    end

    dxDrawImage(posX * (x/1920), 0 * (y/1080), 1920* (x/1920), 1080 * (y/1080), "Files/Images/Radio.png", 0, 0, 0, tocolor(255, 255, 255, 255), false)

    for i = 1, 7 do
        local datay = 470 + (i - 1) * 19
        local entryIndex = i + offset
        if(entryIndex <= #entries) then
            local baseGray = 40 + (i - 1) * 30
            local color = (i == selectedIndex) and tocolor(255, 255, 0, 255) or tocolor(baseGray, baseGray, baseGray, 255)

            dxDrawRectangle((posX + 56) * (x/1920), datay * (y/1080), 131* (x/1920), 19 * (y/1080), color, false)
            dxDrawText(entries[entryIndex][2], (posX + 72) * (x/1920), datay * (y/1080), (posX + 177) * (x/1920), (datay + 19) * (y/1080), tocolor(0, 0, 0, 255), 1.00, "default", "center", "center", false, false, false, false, false)
        else
            break
        end
    end

    dxDrawText(getText("CRadio1"), posX + 28, 678, posX + 215, 769, tocolor(255, 255, 255, 255), 1.00, "default", "center", "center", false, false, false, false, false)
end

function Radio.open()
	if(Radio.visible == false and not(isPedDead(localPlayer)))then
		Radio.visible = true
		posX = -300
		selectedIndex = 1
		offset = 0
		addEventHandler("onClientKey",root,Radio.keyPress)
		addEventHandler("onClientRender",root,Radio.dxDraw)
		triggerServerEvent("Radio.getEntries",localPlayer)
	end
end

function Radio.close()
	if(Radio.visible == true)then
		Radio.visible = false
		removeEventHandler("onClientKey",root,Radio.keyPress)
		removeEventHandler("onClientRender",root,Radio.dxDraw)
	end
end

function Radio.keyPress(button, press)
	if(not(press))then return end
    if(button == "arrow_u")then	
        if selectedIndex > 1 then
            selectedIndex = selectedIndex - 1
        elseif(offset > 0)then
            offset = offset - 1
        end
    elseif(button == "arrow_d")then
        if selectedIndex < 7 and selectedIndex < #entries then
            selectedIndex = selectedIndex + 1
        elseif(offset + 7 < #entries)then
            offset = offset + 1
        end
    elseif(button == "enter")then
        local entryIndex = selectedIndex + offset
        Radio.createBlips(entries[entryIndex][1])
    elseif(button == "backspace")then
        Radio.close()
    end
end

function Radio.createBlips(ID)
	local ID = tonumber(ID)
	if(Radio["Coordinates"][ID])then
		Radio.deleteBlips(ID)
		for i,v in ipairs(Radio["Coordinates"][ID])do
			Radio.Blips[i] = createBlip(v[1],v[2],v[3],53)
		end
	end
end

function Radio.deleteBlips()
	if(#Radio.Blips >= 1)then
		for _,v in pairs(Radio.Blips)do
			destroyElement(v)
		end
	end
end

addEvent("Radio.updateEntries",true)
addEventHandler("Radio.updateEntries",root,function(playerEntries)
	entries = playerEntries
end)

addEventHandler("onClientPlayerWasted",root,function()
	if(source == localPlayer)then
		Radio.close()
	end
end)