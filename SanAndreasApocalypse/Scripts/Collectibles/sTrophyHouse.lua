addEvent("TrophyHouse.MostAchievementPlayer", true)
addEventHandler("TrophyHouse.MostAchievementPlayer", root, function()
    local query = dbQuery(handler, "SELECT name, achievements FROM characters")
    local result = dbPoll(query, -1)
    local players = {}

    for _, row in ipairs(result) do
        local username = row.name
        local achievementString = row.achievements or ""
        local achievementTable = {}

        for id in string.gmatch(achievementString, "%d+") do
            local achievementID = tonumber(id)
            if achievementID and achievementID >= 1 and achievementID <= 300 then
                achievementTable[achievementID] = true
            end
        end

        local count = 0
        for i = 1, #Achievements["Achievements"]["EN"] do
            if achievementTable[i] then
                count = count + 1
            end
        end

        table.insert(players, {username = username, count = count})
    end

    table.sort(players, function(a, b) return a.count > b.count end)

    local top20 = {}
    for i = 1, math.min(25, #players) do
        table.insert(top20, players[i])
    end

    triggerClientEvent(client, "TrophyHouse.ReceiveTopPlayers", client, top20)
end)

