function TrophyHouse.loadData(player)
	if(not(player))then player = client end
	local data = {}
	
	for _,v in pairs(TrophyHouse["Data"][apocalypseGetElementData(player,"language") or "EN"])do
		if(hasPlayerTrophy(client,v[2]) == true)then
			table.insert(data,{v[1],true,v[2]})
		else
			table.insert(data,{v[1],false,v[2]})
		end
	end
	triggerClientEvent(client,"TrophyHouse.updateTrophys",client,data)
end
