addEventHandler("TrophyHouse.loadPlayerAchievements", root, function(playerName)
    if playerName then
        local query = dbQuery(handler, "SELECT achievements FROM characters WHERE name = ?", playerName)
        local result = dbPoll(query, -1)

        if result and result[1] and result[1].achievements then
            local achievementString = result[1].achievements
            local achievementTable = {}

            for id in string.gmatch(achievementString, "%d+") do
                local achievementID = tonumber(id)
                if achievementID then
                    table.insert(achievementTable, achievementID)
                end
            end

            triggerClientEvent(client, "TrophyHouse.receivePlayerAchievements", client, achievementTable)
        else
			
        end
    end
end)