addEvent("TrophyHouse.takeBonus", true)
addEventHandler("TrophyHouse.takeBonus", root, function(ID)
    local ID = tonumber(ID)
    if not ID then return false end

    local characterID = getCharacterID(client)
    if not characterID then return false end

    local result = dbPoll(dbQuery(handler, "SELECT * FROM trophy_timer WHERE character_owner_id = ? AND trophyID = ?", characterID, ID), -1)
	local status = false
	local remainingTime = 0

    if (#result > 0) then
        local currentTimestamp = getRealTime().timestamp
        local trophyTime = tonumber(result[1]["trophyTimer"])

        if (trophyTime == 0) then
            status = true
        elseif (trophyTime > currentTimestamp) then
            remainingTime = trophyTime - currentTimestamp
            status = false
        else
            dbExec(handler, "DELETE FROM trophy_timer WHERE character_owner_id = ? AND trophyID = ?", characterID, ID)
            status = true
        end
    else
        status = true
    end
	
	if(status == true)then
		local money = TrophyHouse["Bonus"][ID].money
		local experience = TrophyHouse["Bonus"][ID].experiencePoints
		dbExec(handler,"INSERT INTO trophy_timer (character_owner_id,trophyTimer,trophyID) VALUES ('"..characterID.."','"..getRealTime().timestamp + TrophyHouse["Bonus"][ID].resetTimer.."','"..ID.."')")
		NPC.MeMessage(client,getText(client,"STrophyHouse5"):format(money,experience))
		givePlayerServerMoney(client,money)
		giveEXP(client,experience)
		outputLog(getPlayerName(client).." hat "..experience.." EXP und $"..money.." eingesammelt", "Trophaen", getCharacterID(player))
	else
		NPC.MeMessage(client,getText(client,"STrophyHouse4"):format(formatTimeLeft(remainingTime)))
	end
end)

function hasPlayerTrophy(player,ID)
	local ID = tonumber(ID)
	local characterID = getCharacterID(player)
	local playerTrophys = getPlayerData("characters","ID",characterID,"trophys")
	
	if(not(playerTrophys))then
		dbExec(handler,"UPDATE characters set trophys = '' WHERE ID = '"..characterID.."'")
		playerTrophys = getPlayerData("characters","ID",characterID,"trophys")
	end
	
	local values = split(playerTrophys,"|")
	local hasTrophy = false
	
	if(playerTrophys and ID)then
		for _,v in pairs(values)do
			if(tonumber(v) == ID)then
				hasTrophy = true
				break
			end
		end
	end
	return hasTrophy
end

function setTrophy(player,ID)
	local ID = tonumber(ID)
	if(hasPlayerTrophy(player,ID) == false)then
		local characterID = getCharacterID(player)
		local playerTrophys = getPlayerData("characters","ID",characterID,"trophys")
		dbExec(handler,"UPDATE characters SET trophys = '"..playerTrophys..ID.."|' WHERE ID = '"..characterID.."'")
		outputLog(getPlayerName(player).." hat eine Trophäe bekommen (ID: "..ID..")", "Trophaen", getCharacterID(player))
		NPC.MeMessage(player,getText(player,"STrophyHouse2"))
	else
		NPC.MeMessage(player,getText(player,"STrophyHouse3"))
	end
end

