function hasPlayerCollectiblePickup(player, collectibleType, collectibleID)
	local CharacterID = getCharacterID(player)
	if(not(CharacterID))then return false end
	
	local query = dbQuery(handler,"SELECT * FROM collectible_pickups WHERE character_id = ? AND collectible_type = ? and collectible_id = ?", CharacterID, collectibleType, collectibleID)
	local result = dbPoll(query,-1)
	
	return result and #result > 0
end

function addCollectiblePickup(player, collectibleType, collectibleID)
	if(not(hasPlayerCollectiblePickup(player, collectibleType, collectibleID)))then
		local CharacterID = getCharacterID(player)
		if(not(CharacterID))then return false end
		dbExec(handler,"INSERT INTO collectible_pickups (character_id, collectible_type, collectible_id) VALUES (?,?,?)", CharacterID, collectibleType, collectibleID)
		NPC.MeMessage(player,getText(player,"MeMessage26"))
		giveItem(player,180,1)
		
		local bonuspoints_collectibles = getPlayerData("character_stats","character_id",getCharacterID(player),"bonuspoints_collectibles")
		Characters.addStats(player,"bonuspoints_collectibles",bonuspoints_collectibles + 1)
		for _,v in pairs(Achievements)do
			if(bonuspoints_collectibles + 1 >= v[1])then
				setAchievement(player,v[2])
			end
		end
		
		outputLog(getPlayerName(player).." hat ein Collectible eingesammelt ("..collectibleType..", ID: "..collectibleID..")", "Collectibles", getCharacterID(player))
	end
end

function CollectiblePickups.load(player, Type)
	if(Type == "HorseShoes")then
		for i, v in ipairs(CollectiblePickups["HorseShoes"]) do
			if(not(hasPlayerCollectiblePickup(player, "HorseShoes", i))) then
				triggerClientEvent(player, "CollectiblePickups.create", player, 954, v[1], v[2], v[3], i, "HorseShoes")
			end
		end
	elseif(Type == "GTA3")then
		for i, v in ipairs(CollectiblePickups["GTA3"]) do
			if(not(hasPlayerCollectiblePickup(player, "GTA3", i))) then
				triggerClientEvent(player, "CollectiblePickups.create", player, 1248, v[1], v[2], v[3], i, "GTA3")
			end
		end
	elseif(Type == "Tiki")then
		for i, v in ipairs(CollectiblePickups["Tiki"]) do
			if(not(hasPlayerCollectiblePickup(player, "Tiki", i))) then
				triggerClientEvent(player, "CollectiblePickups.create", player, 1276, v[1], v[2], v[3], i, "Tiki")
			end
		end
	elseif(Type == "Package")then
		for i, v in ipairs(CollectiblePickups["Package"]) do
			if(not(hasPlayerCollectiblePickup(player, "Package", i))) then
				if(v[4])then int = v[4] else int = 0 end
				triggerClientEvent(player, "CollectiblePickups.create", player, 1279, v[1], v[2], v[3], i, "Package", int)
			end
		end
	end
end

