local TRANSPORTER_ACTIVE_TIME = 15 * 60 * 1000
local TRANSPORTER_RESPAWN_TIME = 15 * 60 * 1000

addEvent("Money_Transporter.requestSync", true)
addEvent("Money_Transporter.dropPlayerBag", true)

function Money_Transporter.getVehicleSyncData(vehicle)
	if not isElement(vehicle) then return nil end

	return {
		vehicle = vehicle,
		started = apocalypseGetElementData(vehicle, "Money_Transporter_Started") or false,
		burnAt = apocalypseGetElementData(vehicle, "Money_Transporter_BurnAt") or false,
		moneybags = tonumber(apocalypseGetElementData(vehicle, "Vehicle_Moneybags")) or 0
	}
end

function Money_Transporter.sendFullSync(player)
	if not isElement(player) then return end

	local list = {}
	for _, vehicle in pairs(Money_Transporter.Vehicles) do
		if isElement(vehicle) then
			table.insert(list, Money_Transporter.getVehicleSyncData(vehicle))
		end
	end

	triggerClientEvent(player, "Money_Transporter.fullSync", resourceRoot, list)
end

function Money_Transporter.broadcastVehicleAdd(vehicle)
	if not isElement(vehicle) then return end
	triggerClientEvent(root, "Money_Transporter.syncAdd", resourceRoot, Money_Transporter.getVehicleSyncData(vehicle))
end

function Money_Transporter.broadcastVehicleUpdate(vehicle)
	if not isElement(vehicle) then return end
	triggerClientEvent(root, "Money_Transporter.syncUpdate", resourceRoot, Money_Transporter.getVehicleSyncData(vehicle))
end

function Money_Transporter.broadcastVehicleRemove(vehicle)
	triggerClientEvent(root, "Money_Transporter.syncRemove", resourceRoot, vehicle)
end

addEventHandler("Money_Transporter.requestSync", root, function()
	if client and isElement(client) then
		Money_Transporter.sendFullSync(client)
	end
end)

function Money_Transporter.setVehicleMoneybags(vehicle, value)
	if not isElement(vehicle) then return end
	apocalypseSetElementData(vehicle, "Vehicle_Moneybags", value)
	Money_Transporter.broadcastVehicleUpdate(vehicle)
end

function Money_Transporter.setVehicleStarted(vehicle, value)
	if not isElement(vehicle) then return end
	apocalypseSetElementData(vehicle, "Money_Transporter_Started", value)
	Money_Transporter.broadcastVehicleUpdate(vehicle)
end

function Money_Transporter.setVehicleBurnAt(vehicle, value)
	if not isElement(vehicle) then return end
	apocalypseSetElementData(vehicle, "Money_Transporter_BurnAt", value)
	Money_Transporter.broadcastVehicleUpdate(vehicle)
end

function Money_Transporter.clearVehicleTimers(id)
	if Money_Transporter.BurnTimers[id] and isTimer(Money_Transporter.BurnTimers[id]) then
		killTimer(Money_Transporter.BurnTimers[id])
	end
	if Money_Transporter.RespawnTimers[id] and isTimer(Money_Transporter.RespawnTimers[id]) then
		killTimer(Money_Transporter.RespawnTimers[id])
	end
	Money_Transporter.BurnTimers[id] = nil
	Money_Transporter.RespawnTimers[id] = nil
end

function Money_Transporter.destroyVehiclePickup(id)
	if Money_Transporter.VehiclePickups[id] and isElement(Money_Transporter.VehiclePickups[id]) then
		destroyElement(Money_Transporter.VehiclePickups[id])
	end
	Money_Transporter.VehiclePickups[id] = nil
end

function Money_Transporter.createVehiclePickup(vehicle)
	if not isElement(vehicle) then return end

	local id = apocalypseGetElementData(vehicle, "Money_Transporter_ID")
	if not id then return end

	Money_Transporter.destroyVehiclePickup(id)

	local x, y, z = getElementPosition(vehicle)
	local pickup = createMarker(x, y, z, "cylinder", 10, 50, 0, 0, 0)

	if isElement(pickup) then
		Money_Transporter.VehiclePickups[id] = pickup
		setElementDimension(pickup, getElementDimension(vehicle))
		setElementInterior(pickup, getElementInterior(vehicle))

		addEventHandler("onMarkerHit", pickup, function(player)
			if getElementType(player) == "player" then
				if getElementDimension(player) == getElementDimension(source) then
					triggerClientEvent(player, "showInformationHelpBar", player, getText(player, "CMoneyTransporter3"), getText(player, "CMoneyTransporter1"))
				end
			end
		end)
	end
end

function Money_Transporter.scheduleRespawn(id, delay)
	Money_Transporter.clearVehicleTimers(id)
	Money_Transporter.destroyVehiclePickup(id)

	Money_Transporter.RespawnTimers[id] = setTimer(function(transporterID)
		Money_Transporter.load(transporterID)
		Money_Transporter.createMoneyBags()
	end, delay, 1, id)
end

function Money_Transporter.startBurnCountdown(vehicle)
	if not isElement(vehicle) then return end

	local id = apocalypseGetElementData(vehicle, "Money_Transporter_ID")
	if not id then return end

	if Money_Transporter.BurnTimers[id] and isTimer(Money_Transporter.BurnTimers[id]) then
		killTimer(Money_Transporter.BurnTimers[id])
	end

	local burnAt = getRealTime().timestamp + math.floor(TRANSPORTER_ACTIVE_TIME / 1000)
	Money_Transporter.setVehicleBurnAt(vehicle, burnAt)

	Money_Transporter.BurnTimers[id] = setTimer(function(v, transporterID)
		if not isElement(v) then return end

		Money_Transporter.setVehicleBurnAt(v, false)

		local occupants = getVehicleOccupants(v)
		if occupants then
			for _, player in pairs(occupants) do
				if isElement(player) then
					triggerClientEvent(player, "Money_Transporter.destroyMarker", player)
				end
			end
		end

		setElementHealth(v, 0)
	end, TRANSPORTER_ACTIVE_TIME, 1, vehicle, id)
end

function Money_Transporter.giveBagToPlayer(player, bagID, bagValue)
	if not isElement(player) then return false end

	if isElement(Money_Transporter.playerBag[player]) then
		destroyElement(Money_Transporter.playerBag[player])
	end

	Money_Transporter.playerBagID[player] = bagID or false
	Money_Transporter.playerBagValue[player] = bagValue or false

	setPedAnimation(player, "CARRY", "crry_prtial", 50)
	Money_Transporter.playerBag[player] = createObject(1550, 0, 0, 0, 0, 0, 0)
	attachElements(Money_Transporter.playerBag[player], player, 0, 0.4, 0.5)
	setElementCollisionsEnabled(Money_Transporter.playerBag[player], false)

	toggleControl(player, "sprint", false)
	toggleControl(player, "jump", false)
	toggleControl(player, "fire", false)

	unbindKey(player, "e", "down", Money_Transporter.dropPlayerBag)
	bindKey(player, "e", "down", Money_Transporter.dropPlayerBag)
	triggerClientEvent(player,"createActivitiesInformationText",player,getText(player,"SMoneyTransporter10"))
	return true
end

function Money_Transporter.createPlayerBag(player)
	return Money_Transporter.giveBagToPlayer(player, false, false)
end

function Money_Transporter.createDroppedBag(x, y, z, dimension, interior, bagID, bagValue)
	local object = createObject(1550, x, y, z + 0.26, 0, 0, math.random(0, 360))
	if not isElement(object) then return false end

	setElementDimension(object, dimension or 0)
	setElementInterior(object, interior or 0)

	apocalypseSetElementData(object, "Money_Transporter_Moneybag_ID", bagID or false)
	apocalypseSetElementData(object, "Money_Transporter_Moneybag", bagValue or false)

	if bagID then
		Money_Transporter.MoneybagObjects[bagID] = object
	end

	addEventHandler("onElementClicked", object, function(button, state, player)
		if button ~= "left" or state ~= "down" then return end
		if getElementType(player) ~= "player" then return end

		if not isElement(Money_Transporter.playerBag[player]) then
			local index = apocalypseGetElementData(source, "Money_Transporter_Moneybag_ID")
			local value = apocalypseGetElementData(source, "Money_Transporter_Moneybag")

			if index and Money_Transporter.MoneybagObjects[index] == source then
				Money_Transporter.MoneybagObjects[index] = nil
			end

			destroyElement(source)
			Money_Transporter.giveBagToPlayer(player, index, value)
		else
			NPC.MeMessage(player, getText(player, "SMoneyTransporter7"))
		end
	end)

	return object
end

function Money_Transporter.dropPlayerBag(player)
	if not player then
		player = client
	end

	if not isElement(player) then return end
	if not isElement(Money_Transporter.playerBag[player]) then return end

	local bagID = Money_Transporter.playerBagID[player]
	local bagValue = Money_Transporter.playerBagValue[player]

	local x, y, z = getElementPosition(player)
	local _, _, rz = getElementRotation(player)

	if isElement(Money_Transporter.playerBag[player]) then
		destroyElement(Money_Transporter.playerBag[player])
	end

	Money_Transporter.playerBag[player] = nil
	Money_Transporter.playerBagID[player] = nil
	Money_Transporter.playerBagValue[player] = nil

	setPedAnimation(player)
	toggleControl(player, "sprint", true)
	toggleControl(player, "jump", true)
	toggleControl(player, "fire", true)
	unbindKey(player, "e", "down", Money_Transporter.dropPlayerBag)

	setPedAnimation(player, "ped", "WOMAN_walknorm")
	setTimer(function(plr)
		if isElement(plr) then
			setPedAnimation(plr)
		end
	end, 50, 1, player)

	local forward = 1.0
	local rad = math.rad(rz)
	local dropX = x + math.sin(rad) * forward
	local dropY = y + math.cos(rad) * forward
	local dropZ = z - 0.9

	Money_Transporter.createDroppedBag(
		dropX,
		dropY,
		dropZ,
		getElementDimension(player),
		getElementInterior(player),
		bagID,
		bagValue
	)
end

addEventHandler("Money_Transporter.dropPlayerBag", root, function()
	if client and isElement(client) then
		Money_Transporter.dropPlayerBag(client)
	end
end)

function Money_Transporter.load(ID)
	local i = ID
	if isElement(Money_Transporter.Vehicles[i]) then return end

	local tbl = Money_Transporter["VehSpawns"][i]
	local x, y, z, rx, ry, rz = tbl[1], tbl[2], tbl[3], tbl[4], tbl[5], tbl[6]

	Money_Transporter.Vehicles[i] = createVehicle(428, x, y, z, rx, ry, rz)
	local vehicle = Money_Transporter.Vehicles[i]

	setVehicleColor(vehicle, 0, 0, 0)

	apocalypseSetElementData(vehicle, "Vehicle_Moneybags", 0)
	apocalypseSetElementData(vehicle, "Money_Transporter_ID", i)
	apocalypseSetElementData(vehicle, "Money_Transporter_Started", false)
	apocalypseSetElementData(vehicle, "Money_Transporter_BurnAt", false)

	setElementFrozen(vehicle, true)

	Money_Transporter.broadcastVehicleAdd(vehicle)
	Money_Transporter.createVehiclePickup(vehicle)

	addEventHandler("onVehicleStartEnter", vehicle, function(player, seat)
		if seat == 0 then
			if apocalypseGetElementData(player, "colony") < 1 then
				cancelEvent()
			end
		end
	end)

	addEventHandler("onVehicleEnter", vehicle, function(player, seat)
		if seat == 0 then
			local moneybags = tonumber(apocalypseGetElementData(source, "Vehicle_Moneybags")) or 0

			if moneybags >= 5 then
				local pos = Shelter.getColonyShelterPosition(apocalypseGetElementData(player, "colony"))
				if pos ~= false then
					local x2, y2, z2 = pos[1], pos[2], pos[3]
					NPC.MeMessage(player, getText(player, "SMoneyTransporter1"))
					triggerClientEvent(player, "Money_Transporter.createMarker", player, x2, y2, z2)
				else
					if apocalypseGetElementData(player, "colony") >= 1 then
						NPC.MeMessage(player, getText(player, "SMoneyTransporter2"))
					else
						NPC.MeMessage(player, getText(player, "SMoneyTransporter9"))
					end
				end
			else
				NPC.MeMessage(player, getText(player, "SMoneyTransporter3"))
			end
		end
	end)

	addEventHandler("onVehicleExit", vehicle, function(player)
		triggerClientEvent(player, "Money_Transporter.destroyMarker", player)
	end)

	addEventHandler("onVehicleExplode", vehicle, function()
		local vx, vy, vz = getElementPosition(source)
		local px, py, pz

		local id = apocalypseGetElementData(source, "Money_Transporter_ID")
		Money_Transporter.broadcastVehicleRemove(source)
		Money_Transporter.destroyVehiclePickup(id)

		local pickupsTbl = {}
		for i2 = 1, 5 do
			if math.random(1, 2) == 1 then
				px, py, pz = vx + 0.3 * i2, vy + math.random(4, 10), vz
			else
				px, py, pz = vx - 0.3 * i2, vy + math.random(4, 10), vz
			end

			local Pickup = createPickup(px, py, pz, 3, 1550, 50)
			table.insert(pickupsTbl, Pickup)

			addEventHandler("onPickupHit", Pickup, function(player)
				destroyElement(source)
				givePlayerServerMoney(player, math.random(15, 25))
			end)
		end

		setTimer(function(Pickups)
			for _, v in pairs(Pickups) do
				if isElement(v) then
					destroyElement(v)
				end
			end
		end, 120000, 1, pickupsTbl)

		Money_Transporter.Vehicles[id] = nil
		Money_Transporter.scheduleRespawn(id, TRANSPORTER_RESPAWN_TIME)

		setTimer(function(Vehicle)
			if isElement(Vehicle) then
				destroyElement(Vehicle)
			end
		end, 120000, 1, source)
	end)

	addEventHandler("onElementDestroy", vehicle, function()
		local id = apocalypseGetElementData(source, "Money_Transporter_ID")
		Money_Transporter.broadcastVehicleRemove(source)
		Money_Transporter.destroyVehiclePickup(id)

		if Money_Transporter.Vehicles[id] == source then
			Money_Transporter.Vehicles[id] = nil
		end
	end)

	addEventHandler("onElementClicked", vehicle, function(button, state, player)
		if getElementType(player) ~= "player" then return end
		if button ~= "right" or state ~= "down" then return end

		local vehicleMoneybags = tonumber(apocalypseGetElementData(source, "Vehicle_Moneybags")) or 0
		local started = apocalypseGetElementData(source, "Money_Transporter_Started")

		if started == false then
			if isElement(Money_Transporter.playerBag[player]) then
				if vehicleMoneybags < 5 then
					if isElement(Money_Transporter.playerBag[player]) then
						destroyElement(Money_Transporter.playerBag[player])
					end

					setPedAnimation(player, "ped", "WOMAN_walknorm")
					setTimer(function(plr)
						if isElement(plr) then
							setPedAnimation(plr)
						end
					end, 50, 1, player)

					unbindKey(player, "e", "down", Money_Transporter.dropPlayerBag)

					Money_Transporter.playerBag[player] = nil
					Money_Transporter.playerBagID[player] = nil
					Money_Transporter.playerBagValue[player] = nil

					toggleControl(player, "sprint", true)
					toggleControl(player, "jump", true)
					toggleControl(player, "fire", true)

					local newMoneybags = vehicleMoneybags + 1
					Money_Transporter.setVehicleMoneybags(source, newMoneybags)

					if newMoneybags >= 5 then
						NPC.MeMessage(player, getText(player, "SMoneyTransporter8"))
						setElementFrozen(source, false)
						Money_Transporter.setVehicleStarted(source, true)
						Money_Transporter.startBurnCountdown(source)
						setAchievement(player, 431)
					end
				else
					NPC.MeMessage(player, getText(player, "SMoneyTransporter4"))
				end
			end
		else
			if vehicleMoneybags >= 1 then
				if not isElement(Money_Transporter.playerBag[player]) then
					local pos = Shelter.getColonyShelterPosition(apocalypseGetElementData(player, "colony"))
					if pos ~= false then
						local x2, y2, z2 = pos[1], pos[2], pos[3]
						local px, py, pz = getElementPosition(player)

						if getDistanceBetweenPoints3D(x2, y2, z2, px, py, pz) <= 25 then
							Money_Transporter.giveBagToPlayer(player, false, false)

							local newMoneybags = vehicleMoneybags - 1
							Money_Transporter.setVehicleMoneybags(source, newMoneybags)

							if newMoneybags <= 0 then
								local id = apocalypseGetElementData(source, "Money_Transporter_ID")
								Money_Transporter.clearVehicleTimers(id)
								Money_Transporter.destroyVehiclePickup(id)
								Money_Transporter.Vehicles[id] = nil
								Money_Transporter.broadcastVehicleRemove(source)

								destroyElement(source)
								Money_Transporter.scheduleRespawn(id, TRANSPORTER_RESPAWN_TIME)
							end
						else
							NPC.MeMessage(player, getText(player, "SMoneyTransporter5"))
						end
					end
				end
			else
				NPC.MeMessage(player, getText(player, "SMoneyTransporter6"))
			end
		end
	end)
end

for i = 1, #Money_Transporter["VehSpawns"] do
	Money_Transporter.load(i)
end

function Money_Transporter.createMoneyBags()
	for i, v in ipairs(Money_Transporter["Moneybags"]) do
		if not isElement(Money_Transporter.MoneybagObjects[i]) then
			Money_Transporter.MoneybagObjects[i] = createObject(1550, v[1], v[2], v[3], 0, 0, math.random(0, 360))
			local object = Money_Transporter.MoneybagObjects[i]

			local bagValue = math.random(125, 250)
			apocalypseSetElementData(object, "Money_Transporter_Moneybag", bagValue)
			apocalypseSetElementData(object, "Money_Transporter_Moneybag_ID", i)
			setElementDimension(object, 0)
			setElementInterior(object, 0)

			addEventHandler("onElementClicked", object, function(button, state, player)
				if button == "left" and state == "down" then
					if not isElement(Money_Transporter.playerBag[player]) then
						local index = apocalypseGetElementData(source, "Money_Transporter_Moneybag_ID")
						local value = apocalypseGetElementData(source, "Money_Transporter_Moneybag")

						destroyElement(source)
						Money_Transporter.MoneybagObjects[index] = nil

						Money_Transporter.giveBagToPlayer(player, index, value)
					else
						NPC.MeMessage(player, getText(player, "SMoneyTransporter7"))
					end
				end
			end)
		end
	end
end
Money_Transporter.createMoneyBags()

function Money_Transporter.hasPlayerMoneyBag(player)
	return isElement(Money_Transporter.playerBag[player])
end

function Money_Transporter.deliverMoneyBag(player)
	if isElement(Money_Transporter.playerBag[player]) then
		local level = tonumber(apocalypseGetElementData(player, "level")) or 0
		local level_bonus = level * 0.5
		if level > 100 then level_bonus = 100 * 0.5 end

		if isElement(Money_Transporter.playerBag[player]) then
			destroyElement(Money_Transporter.playerBag[player])
		end

		Money_Transporter.playerBag[player] = nil
		Money_Transporter.playerBagID[player] = nil
		Money_Transporter.playerBagValue[player] = nil

		toggleControl(player, "sprint", true)
		toggleControl(player, "jump", true)
		toggleControl(player, "fire", true)
		unbindKey(player, "e", "down", Money_Transporter.dropPlayerBag)

		giveEXP(player, 125 + level_bonus)
		giveColonyEXP(player, 250)

		local rnd_money = math.random(50,75)
		giveColonyMoney(player, rnd_money * 2)
		givePlayerServerMoney(player, rnd_money)

		local delivered_money_bags_cash_transporter = tonumber(getPlayerData("character_stats", "character_id", getCharacterID(player), "delivered_money_bags_cash_transporter"))
		Characters.addStats(player, "delivered_money_bags_cash_transporter", delivered_money_bags_cash_transporter + 1)

		for _, v in pairs(Achievements) do
			if delivered_money_bags_cash_transporter + 1 >= v[1] then
				setAchievement(player, v[2])
			end
		end

		outputLog(getPlayerName(player).." hat einen Geldsack abgegeben und "..(125 + level_bonus).." EXP und $"..rnd_money.." bekommen (+ Kolonie EXP: 250, Kolonie Geld: $"..(rnd_money * 2)..")", "Money Transporter", getCharacterID(player))
	end
end

