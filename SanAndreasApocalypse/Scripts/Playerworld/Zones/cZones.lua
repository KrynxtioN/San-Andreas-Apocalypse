local alpha, untilTime = 255, 0
local sw,sh = guiGetScreenSize()

local sw, sh = guiGetScreenSize()

local imgPath = "Files/Images/Bonus_Zone.png"
local imgW, imgH = 516, 316

local targetX = sw - imgW - 20
local targetY = sh - imgH - 20
local startX = sw + imgW

local animTime = 1000
local showTime = 5000

local bonusZoneActive = false
local bonusZoneStartTick = 0

local function renderBonusZone()
    if not bonusZoneActive then
        return
    end

    local now = getTickCount()
    local elapsed = now - bonusZoneStartTick

    local x = startX
    local alpha = 255

    if elapsed <= animTime then
        local progress = elapsed / animTime
        x = interpolateBetween(startX, 0, 0, targetX, 0, 0, progress, "OutQuad")
    elseif elapsed <= animTime + showTime then
        x = targetX
    elseif elapsed <= animTime + showTime + animTime then
        local progress = (elapsed - animTime - showTime) / animTime
        x = interpolateBetween(targetX, 0, 0, startX, 0, 0, progress, "InQuad")
    else
        bonusZoneActive = false
        removeEventHandler("onClientRender", root, renderBonusZone)
        return
    end

    dxDrawImage(x, targetY, imgW, imgH, imgPath, 0, 0, 0, tocolor(255, 255, 255, alpha), false)
end

function showBonusZoneLogo()
    bonusZoneActive = true
    bonusZoneStartTick = getTickCount()

    removeEventHandler("onClientRender", root, renderBonusZone)
    addEventHandler("onClientRender", root, renderBonusZone)
end
addEvent("showBonusZoneLogo",true)
addEventHandler("showBonusZoneLogo",root,showBonusZoneLogo)

function Zones.renderWarning()
	if(getElementInterior(localPlayer) == 0)then
		local time = getTickCount() % 1000
		local alpha = 50 + math.sin(time / 1000 * math.pi) * 100
		local textAlpha = 255 + math.sin(time / 500 * math.pi) * 100

		dxDrawRectangle(0, 0, sw, sh, tocolor(255, 0, 0, alpha))
		
		if(Zones.seconds < 1)then Zones.text = getText("CZones2") end
		dxDrawText(Zones.text, 0, 0, sw, sh, tocolor(255, 255, 255, math.abs(textAlpha)), 2, "default-bold", "center", "center")
	else
		triggerServerEvent("Zones.destroyPlayerEverything",localPlayer)
		removeEventHandler("onClientRender",root,Zones.renderWarning)
	end
end

addEvent("Zones.createWarning",true)
addEventHandler("Zones.createWarning",root,function(seconds)
	Zones.seconds = 10
	Zones.text = getText("CZones1"):format(Zones.seconds)
	addEventHandler("onClientRender",root,Zones.renderWarning)
end)

addEvent("Zones.destroyWarning",true)
addEventHandler("Zones.destroyWarning",root,function()
	removeEventHandler("onClientRender",root,Zones.renderWarning)
end)

addEvent("Zones.updateSeconds",true)
addEventHandler("Zones.updateSeconds",root,function(seconds)
	Zones.seconds = seconds
	Zones.text = getText("CZones1"):format(seconds)
	if(seconds == 0)then
		Zones.text = getText("CZones2")
	end
end)

local NameRendered = false

function Zones.renderZoneName()
	NameRendered = true
	if(getTickCount() < untilTime)then
		if(alpha < 255)then
			alpha = alpha + 5
		end
	else
		alpha = alpha - 5
	end
	if(alpha <= 0)then
		NameRendered = false
		removeEventHandler("onClientRender",root,Zones.renderZoneName)
		return
	end
	if(getElementInterior(localPlayer) == 0)then
		dxDrawText(Zones.currentZone,0,sh*0.1,sw,sh*0.2,tocolor(255,255,255,alpha),1.5,"default-bold","center","center")
	end
end

addEvent("Zones.createZoneName",true)
addEventHandler("Zones.createZoneName",root,function(ZoneID)
	local ZoneID = tonumber(ZoneID)
	Zones.currentZone = Zones["Names"][apocalypseGetElementData(localPlayer,"language") or "EN"][ZoneID]
	
	if(Zones.currentZone)then
		if(NameRendered ~= true)then
			addEventHandler("onClientRender",root,Zones.renderZoneName)
		end
		alpha, untilTime = 0, getTickCount() + 1500
	end
end)