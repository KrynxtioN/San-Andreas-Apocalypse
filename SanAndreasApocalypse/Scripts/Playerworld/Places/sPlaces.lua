function addDiscoveredPlace(player, ID)
    local ID = tonumber(ID)
    if(hasPlayerDiscoveredPlace(player,ID) == false)then
        local playerPlaces = getPlayerData("characters","ID",getCharacterID(player),"places") or ""
        local newPlaces = playerPlaces .. ID .. "|"
        
        dbExec(handler,"UPDATE characters SET places = ? WHERE ID = ?",newPlaces,getCharacterID(player))
		giveEXP(player,1250)
		givePlayerSkillpoint(player,10)

        local placeName = DiscoverPlaces["Data"][apocalypseGetElementData(player, "language") or "EN"][ID][1]
        triggerClientEvent(player,"createInformationMessage",player,getText(player,"SPlaces1"):format(placeName))
		showPlayerSafezones(player)
	else
		local placeName = DiscoverPlaces["Data"][apocalypseGetElementData(player, "language") or "EN"][ID][1]
		triggerClientEvent(player,"createInformationMessage",player,getText(player,"SPlaces2"):format(placeName))
    end
end
addEvent("addDiscoveredPlace", true)
addEventHandler("addDiscoveredPlace", root, addDiscoveredPlace)

function hasPlayerDiscoveredPlace(player,ID)
	local ID = tonumber(ID)
	local playerPlaces = getPlayerData("characters","ID",getCharacterID(player),"places")
	
	if(not(playerPlaces))then
		dbExec(handler,"UPDATE characters SET places = '' WHERE ID = '"..getCharacterID(player).."'")
		playerPlaces = getPlayerData("characters","ID",getCharacterID(player),"places")
	end
	
	local values = split(playerPlaces, "|")
	local hasPlayerPlace = false
	
	if(playerPlaces and ID)then
		for _,v in pairs(values)do
			if(tonumber(v) == ID)then
				hasPlayerPlace = true
				break
			end
		end
	end
	return hasPlayerPlace
end

function DiscoverPlaces.playerLoad(player)
	for i,v in ipairs(DiscoverPlaces["Zones"])do
		if(hasPlayerDiscoveredPlace(player,i) == false)then
			triggerClientEvent(player,"DiscoverPlaces.createZone",player,i,v[1],v[2],v[3],v[4])
		end
	end
end

addEvent("DiscoverPlaces.getData", true)
addEventHandler("DiscoverPlaces.getData", root, function()
    local Data = {}
    local language = apocalypseGetElementData(client, "language") or "EN"
    local placesTable = DiscoverPlaces["Data"][language]

    local owned = {}
    local playerPlaces = getPlayerData("characters", "ID", getCharacterID(client), "places")

    if playerPlaces and playerPlaces ~= "" then
        local values = split(playerPlaces, "|")
        for _, v in ipairs(values) do
            local id = tonumber(v)
            if id then
                owned[id] = true
            end
        end
    end

    for placeID, Table in pairs(placesTable) do
        if Table then
            table.insert(Data, {
                id = placeID,
                name = Table[1],
                description = Table[2],
                unlocked = owned[placeID] or false
            })
        end
    end

    triggerClientEvent(client, "Collectibles.updateData", client, Data)
end)