function Moon.createRocketMarker(ID)
	local x,y,z = Moon["Marker"][ID][1],Moon["Marker"][ID][2],Moon["Marker"][ID][3]
	Moon.rocketMarker = createMarker(x,y,z,"cylinder",1,0,250,250,150)
	
	addEventHandler("onMarkerHit",Moon.rocketMarker,function(player)
		if(getQuestSeriesProgress(player,2,1) >= tonumber(QuestSeries["QuestData"][1]["Stages"][1].required) and getQuestSeriesProgress(player,2,2) >= tonumber(QuestSeries["QuestData"][1]["Stages"][2].required) and getQuestSeriesProgress(player,2,3) >= tonumber(QuestSeries["QuestData"][1]["Stages"][3].required))then
			if(getElementDimension(player) == getElementDimension(source))then
				triggerClientEvent(player,"Moon.openWindow",player,ID)
			end
		else
			NPC.MeMessage(player,getText(player,"SMoon1"))
		end
	end)
end
