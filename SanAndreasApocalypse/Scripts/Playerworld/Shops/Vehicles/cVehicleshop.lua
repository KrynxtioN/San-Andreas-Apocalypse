local x,y = guiGetScreenSize()

local shopVisible = false
local vehiclesPerPage = 10
local currentPage = 1
local totalVehicles = 0
local vehicleWidth, vehicleHeight = 204, 125

function Vehicleshop.renderWindow()
	local bgW, bgH = (vehicleWidth + 20) * 5 + 100, (vehicleHeight + 20) * 2 + 100
	local bgX, bgY = (x - bgW) / 2, (y - bgH) / 2
	dxDrawRectangle(bgX, bgY, bgW, bgH, tocolor(0, 0, 0, 180))
	
	local rows, cols = 2, 5
	local totalVehicleWidth = cols * vehicleWidth + (cols - 1) * 20
	local startX = bgX + (bgW - totalVehicleWidth) / 2
	local startY = bgY + 50
	local index = (currentPage - 1) * vehiclesPerPage

	for row = 0, rows - 1 do
		for col = 0, cols - 1 do
			index = index + 1
			if(index <= totalVehicles)then
				local x = startX + col * (vehicleWidth + 20)
				local y = startY + row * (vehicleHeight + 20)
				
				local vehicleInfos = Vehicleshop["Vehicles"][Vehicleshop.player_shop][index]
				local name,price_money,price_brain,vehicle_level = vehicleInfos[1],vehicleInfos[2],vehicleInfos[2]/100*15,vehicleInfos[5]
				
				if(Vehicleshop.player_shop == 4)then price_race_token = 1000 end

				dxDrawRectangle(x - 2, y - 2, vehicleWidth + 4, vehicleHeight + 4, tocolor(0, 0, 0, 200))
				
				if(tonumber(apocalypseGetElementData(localPlayer,"level")) < vehicle_level)then
					dxDrawText(getText("CVehicles1"):format(vehicle_level), x - 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
					dxDrawText(getText("CVehicles1"):format(vehicle_level), x + 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
					dxDrawText(getText("CVehicles1"):format(vehicle_level), x, y + vehicleHeight / 2 - 9, x + vehicleWidth, y + vehicleHeight, tocolor(255, 0, 0, 255), 0.8, "default-bold", "center", "center")
				else
					dxDrawImage(x, y, vehicleWidth, vehicleHeight, "Files/Images/Vehicles/Vehicle_"..vehicleInfos[4]..".jpg")
					if(isMouseInPosition(x, y, vehicleWidth, vehicleHeight))then
						if(Vehicleshop.player_shop ~= 4)then
							dxDrawText(getText("CVehicles2"):format(price_money, price_brain), x - 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
							dxDrawText(getText("CVehicles2"):format(price_money, price_brain), x + 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
							dxDrawText(getText("CVehicles2"):format(price_money, price_brain), x, y + vehicleHeight / 2 - 9, x + vehicleWidth, y + vehicleHeight, tocolor(0, 255, 0, 255), 0.8, "default-bold", "center", "center")
						else
							dxDrawText(getText("CVehicles14"):format(price_race_token), x - 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
							dxDrawText(getText("CVehicles14"):format(price_race_token), x + 1, y + vehicleHeight / 2 - 10, x + vehicleWidth, y + vehicleHeight, tocolor(0, 0, 0, 255), 0.8, "default-bold", "center", "center")
							dxDrawText(getText("CVehicles14"):format(price_race_token), x, y + vehicleHeight / 2 - 9, x + vehicleWidth, y + vehicleHeight, tocolor(0, 255, 0, 255), 0.8, "default-bold", "center", "center")
						end
					end
				end
			end
		end
	end

	local arrowSize = 40
	if(currentPage > 1)then
		dxDrawText("<", bgX - arrowSize, bgY + bgH / 2 - arrowSize / 2, bgX, bgY + bgH / 2 + arrowSize / 2, tocolor(255, 255, 255, 255), 2, "default-bold", "center", "center")
	end
	
	if(currentPage * vehiclesPerPage < totalVehicles)then
		dxDrawText(">", bgX + bgW, bgY + bgH / 2 - arrowSize / 2, bgX + bgW + arrowSize, bgY + bgH / 2 + arrowSize / 2, tocolor(255, 255, 255, 255), 2, "default-bold", "center", "center")
	end
	dxDrawText(getText("CVehicles3"), bgX, bgY + bgH - 40, bgX + bgW, bgY + bgH, tocolor(255, 255, 255, 255), 1, "default-bold", "center", "center",_,true)
end

function Vehicleshop.handleClick(button, state)
	if(button == "left" and state == "down")then
		local bgW, bgH = (vehicleWidth + 20) * 5 + 100, (vehicleHeight + 20) * 2 + 100
		local bgX, bgY = (x - bgW) / 2, (y - bgH) / 2
		local rows, cols = 2, 5
		local startX = bgX + (bgW - (cols * vehicleWidth + (cols - 1) * 20)) / 2
		local startY = bgY + 50
		local index = (currentPage - 1) * vehiclesPerPage
		local arrowSize = 40

		if(isMouseInPosition(bgX - arrowSize, bgY + bgH / 2 - arrowSize / 2, arrowSize, arrowSize))then
			currentPage = currentPage - 1
			return
		end

		if(isMouseInPosition(bgX + bgW, bgY + bgH / 2 - arrowSize / 2, arrowSize, arrowSize))then
			currentPage = currentPage + 1
			return
		end

		for row = 0, rows - 1 do
			for col = 0, cols - 1 do
				index = index + 1
				if(index <= totalVehicles)then
					local x = startX + col * (vehicleWidth + 20)
					local y = startY + row * (vehicleHeight + 20)

					if(isMouseInPosition(x, y, vehicleWidth, vehicleHeight))then
						local vehicleInfos = Vehicleshop["Vehicles"][Vehicleshop.player_shop][index]
						local price_money,price_brain,vehicle_model,vehicle_level = vehicleInfos[2],vehicleInfos[2]/100*15,vehicleInfos[4],vehicleInfos[5]
						if(tonumber(apocalypseGetElementData(localPlayer,"level")) >= vehicle_level)then
							triggerServerEvent("Vehicleshop.buy",localPlayer,vehicle_model,vehicle_level,price_money,price_brain)
						end
						return
					end
				end
			end
		end
	end
end

local screenWidth, screenHeight = guiGetScreenSize()
local windowWidth, windowHeight = 300, 200
local windowX, windowY = (screenWidth - windowWidth) / 2, (screenHeight - windowHeight) / 2

function Vehicleshop.renderSpecialWindow()
    dxDrawRectangle(windowX, windowY, windowWidth, windowHeight, tocolor(0, 0, 0, 200))
    dxDrawText(getText("CVehicles5"):format(Vehicleshop["SpecialVehicles"][Vehicleshop.specialVehicleID][1],Vehicleshop["SpecialVehicles"][Vehicleshop.specialVehicleID][2],Vehicleshop["SpecialVehicles"][Vehicleshop.specialVehicleID][3]), windowX, windowY + 10, windowX + windowWidth, windowY + 30, tocolor(255, 255, 255), 1, "default", "center", "top")

    local imageWidth, imageHeight = 150, 100
    local imageX, imageY = windowX + (windowWidth - imageWidth) / 2, windowY + 40
    dxDrawImage(imageX, imageY, imageWidth, imageHeight, "Files/Images/Vehicles/Vehicle_"..Vehicleshop.specialVehicleID..".jpg")

    local buttonWidth, buttonHeight = 100, 30
    local buyButtonX, buyButtonY = windowX + 30, windowY + 150
    local closeButtonX, closeButtonY = windowX + 170, windowY + 150

    dxDrawRectangle(buyButtonX, buyButtonY, buttonWidth, buttonHeight, tocolor(0, 150, 0, 200))
    dxDrawText(getText("CVehicles6"), buyButtonX, buyButtonY, buyButtonX + buttonWidth, buyButtonY + buttonHeight, tocolor(255, 255, 255), 1, "default", "center", "center")
    
    dxDrawRectangle(closeButtonX, closeButtonY, buttonWidth, buttonHeight, tocolor(150, 0, 0, 200))
    dxDrawText(getText("CVehicles7"), closeButtonX, closeButtonY, closeButtonX + buttonWidth, closeButtonY + buttonHeight, tocolor(255, 255, 255), 1, "default", "center", "center")
end

function Vehicleshop.specialWindowClick(button, state, x, y)
    if(button == "left" and state == "down")then
        local buyButtonX, buyButtonY = windowX + 30, windowY + 150
        local closeButtonX, closeButtonY = windowX + 170, windowY + 150
        local buttonWidth, buttonHeight = 100, 30

        if(x >= buyButtonX and x <= buyButtonX + buttonWidth and y >= buyButtonY and y <= buyButtonY + buttonHeight)then
			local VehicleID = Vehicleshop.specialVehicleID
			local money, brainmass, level = Vehicleshop["SpecialVehicles"][VehicleID][1],Vehicleshop["SpecialVehicles"][VehicleID][2],Vehicleshop["SpecialVehicles"][VehicleID][3]
            triggerServerEvent("Vehicleshop.buy",localPlayer,VehicleID,level,money,brainmass)
        end

        if(x >= closeButtonX and x <= closeButtonX + buttonWidth and y >= closeButtonY and y <= closeButtonY + buttonHeight)then
			Vehicleshop.close()
        end
    end
end

function Vehicleshop.openWindow(shop_id)
	if(isWindowOpen())then
		Vehicleshop.player_shop = shop_id
		totalVehicles = #Vehicleshop["Vehicles"][shop_id]
		addEventHandler("onClientRender", root, Vehicleshop.renderWindow)
		addEventHandler("onClientClick", root, Vehicleshop.handleClick)
		setWindowData()
		showCursor(true)
		bindKey("backspace", "down", Vehicleshop.close)
		NPC.NormalMessage(getText("CVehicles4"))
	end
end

function Vehicleshop.openSpecialWindow(vehicle)
	if(isWindowOpen() and vehicle)then
		Vehicleshop.specialVehicleID = vehicle
		addEventHandler("onClientRender",root,Vehicleshop.renderSpecialWindow)
		addEventHandler("onClientClick",root,Vehicleshop.specialWindowClick)
		setWindowData()
		showCursor(true)
		NPC.NormalMessage(getText("CVehicles4"))
	end
end
addEvent("Vehicleshop.openSpecialWindow",true)
addEventHandler("Vehicleshop.openSpecialWindow",root,Vehicleshop.openSpecialWindow)

function Vehicleshop.close()
	removeEventHandler("onClientRender", root, Vehicleshop.renderWindow)
	removeEventHandler("onClientClick", root, Vehicleshop.handleClick)
	closeWindow()
	unbindKey("backspace", "down", Vehicleshop.close)
	NPC.Close()
	removeEventHandler("onClientRender",root,Vehicleshop.renderSpecialWindow)
	removeEventHandler("onClientClick",root,Vehicleshop.specialWindowClick)
end

addEventHandler("onClientPlayerWasted", root, function()
	if(source == localPlayer)then
		Vehicleshop.close()
	end
end)