local x, y = guiGetScreenSize()

local shopVisible = false
local FishersPerPage = 8
local currentPage = 1
local totalFishers = 0
local FisherWidth, FisherHeight = 220, 200
local ITEM_IMG_SIZE = 128

function FishersShop.renderWindow()
	local bgW, bgH = (FisherWidth + 20) * 4 + 80, (FisherHeight + 20) * 2 + 80
	local bgX, bgY = (x - bgW) / 2, (y - bgH) / 2

	local title = getText("CFishershop4")
	local titleHeight = 25
	local titleY = bgY - titleHeight - 10
	dxDrawText(title, bgX, titleY, bgX + bgW, titleY + titleHeight, tocolor(255, 255, 255, 255), 1.5, "default-bold", "center", "center")

	dxDrawRectangle(bgX - 6, bgY - 6, bgW + 12, bgH + 12, tocolor(220, 25, 25, 220))
	dxDrawRectangle(bgX, bgY, bgW, bgH, tocolor(40, 40, 40, 200))
	
	local rows, cols = 2, 4
	local totalFisherWidth = cols * FisherWidth + (cols - 1) * 20
	local startX = bgX + (bgW - totalFisherWidth) / 2
	local startY = bgY + 40
	local index = (currentPage - 1) * FishersPerPage
	
	for row = 0, rows - 1 do
		for col = 0, cols - 1 do
			index = index + 1
			if index <= totalFishers then
				local xPos = startX + col * (FisherWidth + 20)
				local yPos = startY + row * (FisherHeight + 20)
				
				local FisherInfos = FishersShop["Fishers"][FishersShop.player_shop][apocalypseGetElementData(localPlayer, "language") or "EN"][index]
				local name, price_shells, image, itemID, neededlevel = FisherInfos[1], FisherInfos[2], FisherInfos[3], FisherInfos[4], FisherInfos[5] or 0
				
				local hovered = isMouseInPosition(xPos, yPos, FisherWidth, FisherHeight)
				local scale = hovered and 1.1 or 1
				local drawWidth = FisherWidth * scale
				local drawHeight = FisherHeight * scale
				local drawX = xPos - (drawWidth - FisherWidth) / 2
				local drawY = yPos - (drawHeight - FisherHeight) / 2
				
				if(tonumber(apocalypseGetElementData(localPlayer,"level")) >= neededlevel)then
					local r,g,b = 0,255,255
					local infoText = getText("CFishershop2"):format(price_shells, name)
					local rectHeight = 50
					local rectY = drawY + drawHeight - rectHeight
					
					if(itemID == 64)then
						if(hasPlayerItem(64) >= 1 or hasPlayerItem(106) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					if(itemID == 65)then
						if(hasPlayerItem(64) >= 1 or hasPlayerItem(106) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					if(itemID == 66)then
						if(hasPlayerItem(64) >= 1 or hasPlayerItem(106) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					if(itemID == 93)then
						if(hasPlayerItem(93) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					if(itemID == 103)then
						if(hasPlayerItem(103) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					if(itemID == 104)then
						if(hasPlayerItem(104) >= 1)then
							infoText = getText("CFishershop6")
							r,g,b = 255,0,0
						end
					end
					
					if hovered then
						dxDrawRectangle(drawX - 4, drawY - 4, drawWidth + 8, drawHeight + 8, tocolor(r,g,b, 150))
					end

					-- Card Background
					dxDrawRectangle(drawX, drawY, drawWidth, drawHeight, tocolor(20, 20, 20, 200))
					dxDrawRectangle(drawX - 2, drawY - 2, drawWidth + 4, drawHeight + 4, tocolor(0, 0, 0, 220))

					-- Image centered (128x128)
					local imgX = drawX + (drawWidth - ITEM_IMG_SIZE) / 2
					local imgY = drawY + 15
					dxDrawImage(imgX, imgY, ITEM_IMG_SIZE, ITEM_IMG_SIZE, image)

					-- Info bar bottom
					local rectHeight = 45
					local rectY = drawY + drawHeight - rectHeight
					dxDrawRectangle(drawX, rectY, drawWidth, rectHeight, tocolor(0, 0, 0, 170))

					dxDrawText(infoText, drawX + 5, rectY, drawX + drawWidth - 5, rectY + rectHeight, tocolor(255, 255, 255, 255), 1, "default-bold", "center", "center", true, true)
				else
					if hovered then
						dxDrawRectangle(drawX - 4, drawY - 4, drawWidth + 8, drawHeight + 8, tocolor(255, 0, 0, 150))
					end
					
					local rectHeight = 50
					local rectY = drawY + drawHeight - rectHeight
					dxDrawImage(drawX, drawY, drawWidth, drawHeight, image)
					dxDrawRectangle(drawX - 2, drawY - 2, drawWidth + 4, drawHeight + 4, tocolor(0, 0, 0, 200))
					dxDrawText(getText("CFishershop5"):format(neededlevel), drawX, rectY, drawX + drawWidth, rectY + rectHeight, tocolor(255, 0, 0, 255), 1, "default-bold", "center", "center")
				end
			end
		end
	end

	local arrowSize = 35
	if currentPage > 1 then
		dxDrawText("<", bgX - arrowSize, bgY + bgH/2 - arrowSize/2, bgX, bgY + bgH/2 + arrowSize/2, tocolor(255, 255, 255, 255), 2, "default-bold", "center", "center")
	end
	
	if currentPage * FishersPerPage < totalFishers then
		dxDrawText(">", bgX + bgW, bgY + bgH/2 - arrowSize/2, bgX + bgW + arrowSize, bgY + bgH/2 + arrowSize/2, tocolor(255, 255, 255, 255), 2, "default-bold", "center", "center")
	end
	
	dxDrawText(getText("CFishershop3"), bgX, bgY + bgH - 30, bgX + bgW, bgY + bgH, tocolor(255, 255, 255, 255), 1, "default-bold", "center", "center", _, true)
end

function FishersShop.handleClick(button, state)
	if button == "left" and state == "down" then
		local bgW, bgH = (FisherWidth + 20) * 4 + 80, (FisherHeight + 20) * 2 + 80
		local bgX, bgY = (x - bgW) / 2, (y - bgH) / 2
		local rows, cols = 2, 4
		local startX = bgX + (bgW - (cols * FisherWidth + (cols - 1) * 20)) / 2
		local startY = bgY + 40
		local index = (currentPage - 1) * FishersPerPage
		local arrowSize = 35

		if isMouseInPosition(bgX - arrowSize, bgY + bgH/2 - arrowSize/2, arrowSize, arrowSize) then
			currentPage = currentPage - 1
			if currentPage < 1 then currentPage = 1 end
			return
		end

		if isMouseInPosition(bgX + bgW, bgY + bgH/2 - arrowSize/2, arrowSize, arrowSize) then
			currentPage = currentPage + 1
			local maxPage = math.ceil(totalFishers / FishersPerPage)
			if currentPage > maxPage then currentPage = maxPage end
			return
		end
		
		if isMouseInPosition(bgX, bgY + bgH - 30, bgX + bgW, bgY + bgH) then
			FishersShop.close()
		end
	
		for row = 0, rows - 1 do
			for col = 0, cols - 1 do
				index = index + 1
				if index <= totalFishers then
					local xPos = startX + col * (FisherWidth + 20)
					local yPos = startY + row * (FisherHeight + 20)
	
					if isMouseInPosition(xPos, yPos, FisherWidth, FisherHeight) then
						local FisherInfos = FishersShop["Fishers"][FishersShop.player_shop][apocalypseGetElementData(localPlayer, "language") or "EN"][index]
						local price_shells = FisherInfos[2]
						local FisherID = FisherInfos[4]
						triggerServerEvent("FishersShop.buy", localPlayer, FisherID, price_shells)
						return
					end
				end
			end
		end
	end
end

function FishersShop.openWindow(shop_id)
	if isWindowOpen() then
		FishersShop.player_shop = shop_id
		currentPage = 1
		totalFishers = #FishersShop["Fishers"][shop_id][apocalypseGetElementData(localPlayer, "language") or "EN"]
		addEventHandler("onClientRender", root, FishersShop.renderWindow)
		addEventHandler("onClientClick", root, FishersShop.handleClick)
		setWindowData()
		showCursor(true)
		bindKey("backspace", "down", FishersShop.close)
	end
end

function FishersShop.close()
	removeEventHandler("onClientRender", root, FishersShop.renderWindow)
	removeEventHandler("onClientClick", root, FishersShop.handleClick)
	closeWindow()
	unbindKey("backspace", "down", FishersShop.close)
	NPC.Close()
end

addEventHandler("onClientPlayerWasted", root, function()
	if source == localPlayer then
		FishersShop.close()
	end
end)