function Moebel.showObject()
	Moebel.id = 1
	Moebel.object = createObject(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][1],1404.414,-1625.174,15.563,0,0,0)
	setElementAlpha(Moebel.object,255)
	setElementDoubleSided(Moebel.object,true)

	setCameraMatrix(1404.288,-1614.615,15.194,1404.301,-1615.614,15.144)
	setElementAlpha(localPlayer,0)

	bindKey("arrow_r","down",Moebel.right)
	bindKey("arrow_l","down",Moebel.left)
	bindKey("enter","down",Moebel.buy)
	bindKey("backspace","down",Moebel.beenden)

	setElementFrozen(localPlayer,true)
	addEventHandler("onClientRender",root,Moebel.rotate)
	addEventHandler("onClientRender",root,Moebel.information)
	
	Moebel.preis = Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][3]
	Moebel.text = getText("CFurniture1"):format(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][2],Moebel.preis)
end

addCommandHandler("furniture",function()
Moebel.showObject()
end)

function Moebel.beenden()
	if isElement(Moebel.object) then destroyElement(Moebel.object) end
	unbindKey("arrow_r","down",Moebel.right)
	unbindKey("arrow_l","down",Moebel.left)
	unbindKey("enter","down",Moebel.buy)
	unbindKey("backspace","down",Moebel.beenden)
	setCameraTarget(localPlayer)
	setElementFrozen(localPlayer,false)
	setElementAlpha(localPlayer,255)
	removeEventHandler("onClientRender",root,Moebel.rotate)
	removeEventHandler("onClientRender",root,Moebel.information)
end

function Moebel.right()
	if Moebel.id < #Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"] then
		Moebel.id = Moebel.id + 1
		if isElement(Moebel.object) then destroyElement(Moebel.object) end
		Moebel.object = createObject(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][1], 1404.414, -1625.174, 15.563, 0, 0, 0)
		setElementAlpha(Moebel.object, 255)
		setElementDoubleSided(Moebel.object, true)
		Moebel.preis = Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][3]
		Moebel.text = getText("CFurniture1"):format(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][2], Moebel.preis)
	end
end

function Moebel.left()
	if Moebel.id > 1 then
		Moebel.id = Moebel.id - 1
		if isElement(Moebel.object) then destroyElement(Moebel.object) end
		Moebel.object = createObject(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][1], 1404.414, -1625.174, 15.563, 0, 0, 0)
		setElementAlpha(Moebel.object, 255)
		setElementDoubleSided(Moebel.object, true)
		Moebel.preis = Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][3]
		Moebel.text = getText("CFurniture1"):format(Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][2], Moebel.preis)
	end
end

function Moebel.buy()
	triggerServerEvent("Moebel.buy",localPlayer,Moebel["Moebel"][apocalypseGetElementData(localPlayer,"language") or "EN"][Moebel.id][1],Moebel.preis)
end

function Moebel.rotate()
	if isElement(Moebel.object) then
		local _,_,z = getElementRotation(Moebel.object)
		setElementRotation(Moebel.object,0,0,z+1)
	end
end

function Moebel.information()
    local sx,sy = guiGetScreenSize()
    dxDrawText(Moebel.text, 0, sy-100, sx, sy, tocolor(255,255,255,255), 1.4, "default-bold", "center", "center")
end

