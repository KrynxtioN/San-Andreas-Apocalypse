addEvent("WeaponDealer.createWindow",true)
addEventHandler("WeaponDealer.createWindow",root,function()
	local marker = false
	for _,v in pairs(WeaponDealer.Marker)do
		if(apocalypseGetElementData(v,"WeaponDealerID"))then
			if(isElementWithinMarker(client,v))then
				marker = v
				break
			end
		end
	end
	if(marker ~= false)then
		if(apocalypseGetElementData(marker,"WeaponDealerStatus") == true)then
			local weaponID = apocalypseGetElementData(marker,"WeaponDealerWeaponID")
			local WeaponDealerID = apocalypseGetElementData(marker,"WeaponDealerID")
			triggerClientEvent(client,"WeaponDealer.createWindow",client,weaponID,WeaponDealer["Ammo"][weaponID],WeaponDealer["Price"][weaponID][1],WeaponDealer["Price"][weaponID][2])
		end
	end
end)

addEvent("WeaponDealer.buy",true)
