	local marker = false
	for _,v in pairs(WeaponDealer.Marker)do
		if(apocalypseGetElementData(v,"WeaponDealerID"))then
			if(isElementWithinMarker(client,v))then
				marker = v
				break
			end
		end
	end
	if(marker ~= false)then
		if(apocalypseGetElementData(marker,"WeaponDealerStatus") == true)then
			if(hasPlayerFreeWeaponSlot(client) == true)then
				local weaponID = apocalypseGetElementData(marker,"WeaponDealerWeaponID")
				local WeaponDealerID = apocalypseGetElementData(marker,"WeaponDealerID")
				local cost_money, cost_weapon_parts = WeaponDealer["Price"][weaponID][1],WeaponDealer["Price"][weaponID][2]
				if(tonumber(apocalypseGetElementData(client,"money")) >= cost_money)then
					if(hasPlayerItem(client,22) >= cost_weapon_parts)then
						PlayerWeapons.addNewWeapon(client,weaponID,tonumber(WeaponDealer["Ammo"][weaponID]))
						apocalypseSetElementData(marker,"WeaponDealerStatus",false)
						apocalypseSetElementData(WeaponDealer.Peds[WeaponDealerID],"WeaponDealerStatus",false)
						triggerClientEvent(client,"WeaponDealer.Close",client)
						takeItem(client,22,cost_weapon_parts)
						apocalypseSetElementData(client,"money",apocalypseGetElementData(client,"money")-cost_money)
						outputLog(getPlayerName(client).." hat sich eine Waffe mit der ID "..weaponID.." für "..cost_weapon_parts.." Waffenteile und $"..cost_money.." gekauft","Weapondealer",getCharacterID(client))
