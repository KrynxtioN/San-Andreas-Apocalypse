end

function HungryThirstyPedMission.create(ID)
	if(not(isElement(HungryThirstyPedMission.Peds[ID])))then
		local tbl = HungryThirstyPedMission["Coordinates"][ID]
		HungryThirstyPedMission.Peds[ID] = createPed(possibleSkinsDecorationPeds[math.random(1,#possibleSkinsDecorationPeds)],tbl[1],tbl[2],tbl[3],tbl[4])
		setElementInterior(HungryThirstyPedMission.Peds[ID],tbl[5])
		setElementDimension(HungryThirstyPedMission.Peds[ID],tbl[6])
		apocalypseSetElementData(HungryThirstyPedMission.Peds[ID],"HungryThirstyPedID",ID)
		setPedAnimation(HungryThirstyPedMission.Peds[ID],"on_lookers","wave_loop")
		setElementFrozen(HungryThirstyPedMission.Peds[ID],true)
		
		HungryThirstyPedMission.Zone[ID] = createColSphere(tbl[1],tbl[2],tbl[3],3)
		setElementInterior(HungryThirstyPedMission.Zone[ID],tbl[5])
		setElementDimension(HungryThirstyPedMission.Zone[ID],tbl[6])
		apocalypseSetElementData(HungryThirstyPedMission.Zone[ID],"HungryThirstyPedID",ID)
		
		addEventHandler("onColShapeHit",HungryThirstyPedMission.Zone[ID],function(player)
			if(getElementType(player) == "player")then
				local ID = tonumber(apocalypseGetElementData(source,"HungryThirstyPedID"))
				local model = getElementModel(HungryThirstyPedMission.Peds[ID])
				if(getElementDimension(player) == getElementDimension(source))then
					if(getElementInterior(player) == getElementInterior(source))then
						outputChatBox(getText(player,"SHungryThirstyPeds1"),player,255,255,255)
					end
				end
			end
		end)
		HungryThirstyPedMission.syncPed(ID)
	end
end

for i = 1,#HungryThirstyPedMission["Coordinates"] do
	HungryThirstyPedMission.create(i)
end

