function HungryThirstyPedMission.syncPed(ID)
	if(isElement(HungryThirstyPedMission.Peds[ID]))then
		HungryThirstyPedMission.ActiveClientPeds[ID] = HungryThirstyPedMission.Peds[ID]
		triggerClientEvent(root,"HungryThirstyPedMission:syncPed",resourceRoot,ID,HungryThirstyPedMission.Peds[ID])
	end
end

function HungryThirstyPedMission.unsyncPed(ID)
	HungryThirstyPedMission.ActiveClientPeds[ID] = nil
