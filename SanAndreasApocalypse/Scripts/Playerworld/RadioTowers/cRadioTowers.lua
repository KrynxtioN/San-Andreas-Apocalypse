function RadioTower.renderInfoText()
	if(isCharacterLoggedIn() and isWindowOpen())then
		for _,v in pairs(RadioTower["Data"])do
			local x1,y1,z1 = v[2],v[3],v[4]
			local screenX1,screenY1 = getScreenFromWorldPosition(x1,y1,z1 + 0.75)
				
			if(screenX1 and screenY1)then
				if(getDistanceBetweenPoints3D(x1,y1,z1,getElementPosition(localPlayer)) <= 5)then
					dxDrawText(getText("CRadioTower1"), screenX1 - 100, screenY1 - 20, screenX1 + 100, screenY1 + 20, tocolor(255, 255, 255), 1.2, "default-bold", "center", "center")
				end
			end
		end
	end
end
addEventHandler("onClientRender",root,RadioTower.renderInfoText)