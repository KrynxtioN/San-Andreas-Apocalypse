local sx, sy = guiGetScreenSize()
local baseX, baseY = 18, 18
local w, h = 360, 110
local icon = 64
local scale = math.max(0.85, math.min(1.0, sx / 1920))

local defaultImgPath = "Files/Images/Bonus/NoBonus.png"

local AUTO_HIDE_AFTER_MS = 10000
local ANIM_TIME_MS = 650
local TAB_VISIBLE_PX = 22

local createdTick = 0
local curX = 0
local fromX, toX = 0, 0
local animStart, animEnd = 0, 0
local targetHidden = false

local activeKey = nil
local stateMode = "bonus"
local stateRemaining = 0
local stateStartTick = 0

local function SERVERBONUS_clientDraw() end

local function startAnim(x)
    fromX = curX
    toX = x
    animStart = getTickCount()
    animEnd = animStart + ANIM_TIME_MS
end

local function isHovering(px, py, pw, ph, tabW, pxHidden)
    if not isCursorShowing() then return false end
    local cx, cy = getCursorPosition()
    if not cx then return false end
    cx, cy = cx*sx, cy*sy

    local onPanel = (cx >= px and cx <= px+pw and cy >= py and cy <= py+ph)
    local onTab   = (cx >= (pxHidden+pw-tabW) and cx <= (pxHidden+pw) and cy >= py and cy <= py+ph)

    return onPanel or onTab
end

local function safeLangKey()
    local lang = apocalypseGetElementData(localPlayer, "language")
    if type(lang) ~= "string" then return "EN" end
    lang = lang:upper()
    if BONUS_TEXT[lang] then return lang end
    return "EN"
end

local function getLangBlock()
    return BONUS_TEXT[safeLangKey()] or BONUS_TEXT.EN
end

local function formatMS(ms)
    ms = math.max(0, math.floor((ms or 0) / 1000))
    local m = math.floor(ms / 60)
    local s = ms % 60
    return string.format("%02d:%02d", m, s)
end

local function getRemaining()
    local passed = getTickCount() - (stateStartTick or getTickCount())
    return math.max(0, (stateRemaining or 0) - passed)
end

local function getBonusStrings(key)
    local L = getLangBlock()

    local remainingStr = nil
    if (stateRemaining or 0) > 0 then
        remainingStr = formatMS(getRemaining())
    end

    if stateMode == "cooldown" then
        local title = L.COOLDOWN_TITLE or L.DEFAULT_TITLE or "SERVER BONUS"
        local desc = ""
        if remainingStr then
            local fmt = L.NEXT_BONUS_IN or "Next bonus in %s"
            desc = string.format(fmt, remainingStr)
        end
        return title, desc, "", defaultImgPath
    end

    local entry = (key and L[key]) or nil
    if (not entry) and key and BONUS_TEXT.EN and BONUS_TEXT.EN[key] then
        entry = BONUS_TEXT.EN[key]
    end

    local title = (entry and entry.title) or (L.DEFAULT_TITLE or "SERVER BONUS")
    local desc  = (entry and entry.desc)  or ""
    if remainingStr then
        local fmt = L.BONUS_ENDS_IN or "Remaining: %s"
        local tail = string.format(fmt, remainingStr)
        desc = (desc ~= "" and (desc .. " • " .. tail)) or tail
    end

    local live  = L.LIVE or (BONUS_TEXT.EN and BONUS_TEXT.EN.LIVE) or "LIVE"
    local image = (entry and entry.image) or defaultImgPath

    return title, desc, live, image
end

addEvent("SERVERBONUS.clientDraw", true)
addEventHandler("SERVERBONUS.clientDraw", root, function(data)
    if type(data) == "table" then
        stateMode = data.mode or "bonus"
        activeKey = data.key
        stateRemaining = tonumber(data.remaining) or 0
        stateStartTick = getTickCount()
    else
        stateMode = "bonus"
        activeKey = data
        stateRemaining = 0
        stateStartTick = getTickCount()
    end

    createdTick = getTickCount()

    local pxVisible = baseX*scale
    curX = pxVisible
    targetHidden = false
    startAnim(pxVisible)

    removeEventHandler("onClientRender", root, SERVERBONUS_clientDraw)
    addEventHandler("onClientRender", root, SERVERBONUS_clientDraw)
end)

function SERVERBONUS_clientDraw()
    local pw, ph = w*scale, h*scale
    local ic = icon*scale

    local pxVisible = baseX*scale
    local py = baseY*scale
    local tabW = TAB_VISIBLE_PX * scale
    local pxHidden = pxVisible - (pw - tabW)

    local now = getTickCount()
    local elapsed = now - createdTick

    local hovering = isHovering(curX, py, pw, ph, tabW, pxHidden)
    local shouldHide = (elapsed >= AUTO_HIDE_AFTER_MS) and (not hovering)

    if shouldHide ~= targetHidden then
        targetHidden = shouldHide
        startAnim(shouldHide and pxHidden or pxVisible)
    end

    if now < animEnd then
        local p = (now - animStart) / (animEnd - animStart)
        curX = interpolateBetween(fromX,0,0, toX,0,0, p, "OutQuad")
    else
        curX = toX
    end

    local pulse = (math.sin(now / 400) + 1) / 2
    local glowA = 70 + pulse * 60

    local title, desc, liveText, image = getBonusStrings(activeKey)
    if type(image) ~= "string" or image == "" then image = defaultImgPath end

    local px = curX

    dxDrawRectangle(px, py, pw, ph, tocolor(10, 12, 18, 185))
    dxDrawRectangle(px, py, pw, 2*scale, tocolor(255, 255, 255, 35))
    dxDrawRectangle(px, py + ph - 2*scale, pw, 2*scale, tocolor(0, 0, 0, 80))

    dxDrawRectangle(px, py, 4*scale, ph, tocolor(220, 25, 25, 200))
    dxDrawRectangle(px - 6*scale, py, 10*scale, ph, tocolor(220, 25, 25, glowA))

    local ix, iy = px + 10*scale, py + (ph - ic)/2
    dxDrawRectangle(ix - 2*scale, iy - 2*scale, ic + 4*scale, ic + 4*scale, tocolor(0,0,0,140))
    dxDrawRectangle(ix - 1*scale, iy - 1*scale, ic + 2*scale, ic + 2*scale, tocolor(255,255,255,25))
    dxDrawImage(ix, iy, ic, ic, image, 0, 0, 0, tocolor(255,255,255,245))

    local tx = ix + ic + 12*scale
    local ty = py + 10*scale
    local textW = pw - (tx - px) - 10*scale

    local titleH = 24*scale
    local gap = 6*scale
    local descY = ty + titleH + gap
    local descH = (py + ph - 10*scale) - descY
    if descH < 0 then descH = 0 end

    dxDrawText(title, tx+1, ty+1, tx+textW+1, ty+titleH+1, tocolor(0,0,0,180), 1.0*scale, "default-bold", "left", "top", true, false)
    dxDrawText(title, tx,   ty,   tx+textW,   ty+titleH,   tocolor(255, 220, 120, 255), 1.0*scale, "default-bold", "left", "top", true, false)

    dxDrawText(desc, tx+1, descY+1, tx+textW+1, descY+descH+1, tocolor(0,0,0,180), 0.95*scale, "default", "left", "top", true, true)
    dxDrawText(desc, tx,   descY,   tx+textW,   descY+descH,   tocolor(210, 235, 255, 240), 0.95*scale, "default", "left", "top", true, true)

    if (not targetHidden) and stateMode ~= "cooldown" then
        local pillW, pillH = 54*scale, 18*scale
        local pillX, pillY = px + pw - pillW - 10*scale, py + 10*scale
        dxDrawRectangle(pillX, pillY, pillW, pillH, tocolor(255, 70, 70, 110 + pulse*80))
        dxDrawText(liveText, pillX, pillY, pillX+pillW, pillY+pillH, tocolor(255,255,255,240), 0.9*scale, "default-bold", "center", "center", true, false)
    end

    if targetHidden then
        dxDrawRectangle(px + pw - tabW, py, tabW, ph, tocolor(255,255,255,8))
    end
	
	if not targetHidden then
		showChat(false)
	else
		showChat(true)
	end
