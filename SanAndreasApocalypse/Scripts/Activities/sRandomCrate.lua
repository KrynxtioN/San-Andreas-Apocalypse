		if(isElement(RandomLootCrate.crateObjects[id]))then
			apocalypseSetElementData(RandomLootCrate.crateObjects[id],"Landed",true)
		end
		if(isElement(RandomLootCrate.parachute[id]))then
			destroyElement(RandomLootCrate.parachute[id])
		end
