local maxCrates = 20

function isAirdropBonusActive()
	if(maxCrates > 20)then
		return true
	else
		return false
	end
end

function RandomLootCrate.updateMaxCrates(amount)
	maxCrates = amount
end

function RandomLootCrate.activateMoreDrops()
	maxCrates = maxCrates + math.random(5,15)
	if(not(isTimer(RandomLootCrate.BonusCrateTimer)))then
		RandomLootCrate.BonusCrateTimer = setTimer(function()
			RandomLootCrate.createCrate()
		end,120000,0)
	end
end

function RandomLootCrate.stopMoreDrops()
	maxCrates = 20
	if(isTimer(RandomLootCrate.BonusCrateTimer))then
		killTimer(RandomLootCrate.BonusCrateTimer)
	end
end

function RandomLootCrate.getFreeSpawn()
	local free = {}

	for i = 1, #RandomLootCrate["Spawn"] do
		if(not isElement(RandomLootCrate.crateObjects[i])) then
			table.insert(free, i)
		end
	end

	if(#free == 0) then
		return false
	end

	return free[math.random(1,#free)]
end

function RandomLootCrate.createCrate()
	if(RandomLootCrate.crate_amount >= maxCrates) then return end

	local rnd = RandomLootCrate.getFreeSpawn()
	if(not rnd) then
		return
	end

	local tbl = RandomLootCrate["Spawn"][rnd]
	local x,y,z = tbl[1],tbl[2],tbl[3]

	RandomLootCrate.crate_amount = RandomLootCrate.crate_amount + 1

	RandomLootCrate.crateObjects[rnd] = createObject(3577,x,y,z+1000)
	RandomLootCrate.parachute[rnd] = createObject(2903,x,y,z+1000)
	RandomLootCrate.sphere[rnd] = createColSphere(x,y,z+1,4)
	apocalypseSetElementData(RandomLootCrate.crateObjects[rnd],"Landed",false)
	apocalypseSetElementData(RandomLootCrate.sphere[rnd],"LootCrateID",rnd)
	apocalypseSetElementData(RandomLootCrate.sphere[rnd],"PlayerIsSearching",false)
	RandomLootCrate.blips[rnd] = createBlip(x,y,z,18,1,0,0,0,255,0,50)

	moveObject(RandomLootCrate.crateObjects[rnd],60000,x,y,z)
	moveObject(RandomLootCrate.parachute[rnd],60000,x,y,z+6.7)
	
