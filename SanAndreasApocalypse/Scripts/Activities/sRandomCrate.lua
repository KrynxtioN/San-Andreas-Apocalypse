								if(isElement(RandomLootCrate.blips[id]))then destroyElement(RandomLootCrate.blips[id])end
								if(isElement(sphere))then destroyElement(sphere)end

								RandomLootCrate.crate_amount = RandomLootCrate.crate_amount - 1
								if(RandomLootCrate.crate_amount < 0)then
									RandomLootCrate.crate_amount = 0
								end

