addEvent("onCancelLootSearch", true)
addEventHandler("onCancelLootSearch", root, function()
	local player = source
	if(apocalypseGetElementData(player,"SearchingDroppedLootCrate") == true)then
		local id = apocalypseGetElementData(player,"LootCrateID")
		if(id and isElement(RandomLootCrate.sphere[id]))then
			if(isTimer(RandomLootCrate.searchTimer[player]))then
				killTimer(RandomLootCrate.searchTimer[player])
			end
			setPedAnimation(player)
			toggleAllControls(player,true)
			apocalypseSetElementData(player,"SearchingDroppedLootCrate",false)
			apocalypseSetElementData(RandomLootCrate.sphere[id],"PlayerIsSearching",false)
			triggerClientEvent(player,"ProgressBar.close",player)
			triggerClientEvent(player,"Airdrop.unbindKey",player)
		end
	end
end)

function RandomLootCrate.giveItems(player)
	local itemAmount = math.random(15,20)
	if(SERVERBONUS.AIRDROP == true)then itemAmount = itemAmount + 5 end
	giveLootItems(player,itemAmount)
	createInfobox(player,getText(player,"SRandomLootCrate1"))
end

function RandomLootCrate.resetData(player)
	if(isTimer(RandomLootCrate.searchTimer[player]))then
		killTimer(RandomLootCrate.searchTimer[player])
		RandomLootCrate.searchTimer[player] = nil
	end

	local id = apocalypseGetElementData(player,"LootCrateID")
	if(id and isElement(RandomLootCrate.sphere[id]))then
		apocalypseSetElementData(RandomLootCrate.sphere[id],"PlayerIsSearching",false)
	end

	apocalypseSetElementData(player,"SearchingDroppedLootCrate",false)
	apocalypseSetElementData(player,"LootCrateID",nil)
	triggerClientEvent(player,"Airdrop.unbindKey",player)
end

function RandomLootCrate.checkBlips(player)
	if(hasPlayerItem(player,5) >= 1)then
		for _,v in pairs(RandomLootCrate.blips)do
			if(isElement(v))then
				setElementVisibleTo(v,player,true)
			end
		end
	end
end

addEventHandler("onPlayerQuit",root,function()
	RandomLootCrate.resetData(source)
end)

addEventHandler("onPlayerWasted",root,function()
	RandomLootCrate.resetData(source)
end)