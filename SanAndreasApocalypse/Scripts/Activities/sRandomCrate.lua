								outputLog(getPlayerName(player).." hat einen Airdrop eingesammelt und "..xp.." EXP und "..skillpoint.." Skillpunkte bekommen","Airdrop",getCharacterID(player))

								if(math.random(1,2) == 1)then
									local r = math.random(1,10)
									if(r <= 5)then
										local items = {72,75}
										giveItem(player,items[math.random(1,#items)],1)
									elseif(r <= 9)then
										local items = {73,76}
										giveItem(player,items[math.random(1,#items)],1)
									else
										local items = {74,77}
										giveItem(player,items[math.random(1,#items)],1)
									end
									NPC.MeMessage(player,getText(player,"SRandomLootCrate3"))
								end

								local airdrops_collected = tonumber(getPlayerData("character_stats","character_id",getCharacterID(player),"airdrops_collected"))
								Characters.addStats(player,"airdrops_collected",airdrops_collected + 1)

								if(DailyTasks.playerTasks[player] and DailyTasks.playerTasks[player][9])then
									DailyTasks.updateProgress(player,9,DailyTasks.playerTasks[player][9].progress + 1)
								end
								if(WeeklyTasks.playerTasks[player] and WeeklyTasks.playerTasks[player][9])then
									WeeklyTasks.updateProgress(player,9,WeeklyTasks.playerTasks[player][9].progress + 1)
								end

								for _,v in pairs(Achievements)do
									if(airdrops_collected + 1 >= v[1])then
										setAchievement(player,v[2])
									end
								end
							end,10000,1,source,player,id)
						end
					end
				end
			end
		end
	end)
end
