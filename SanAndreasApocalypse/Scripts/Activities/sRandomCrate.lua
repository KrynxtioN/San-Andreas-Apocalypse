								toggleAllControls(player,true)
								RandomLootCrate.giveItems(player)

								local Level_Bonus_EXP = tonumber(apocalypseGetElementData(player,"level"))
								if(Level_Bonus_EXP > 100)then Level_Bonus_EXP = 100 end
								local xp = 250 + (15 * Level_Bonus_EXP)
								if(SERVERBONUS.AIRDROP == true)then xp = xp * 2 end
								giveEXP(player,xp)

