local RocketTimer = {}

local function createRhinoAtIndex(index)
    local tbl = RhinoMission.SpawnPosition[index]
    local x, y, z = tbl[1], tbl[2], tbl[3]
    local veh = createVehicle(432, x, y, z, 0, 0, math.random(0, 360))
    RhinoMission.Vehicle[index] = veh
    apocalypseSetElementData(veh, "RhinoMissionID", index)
    setElementFrozen(veh, true)
    setVehicleDamageProof(veh, false)
    setElementHealth(veh, 1000)
	apocalypseSetElementData(veh,"Rocket",true)
	
	addEventHandler("onVehicleEnter",RhinoMission.Vehicle[index],function(player)
		if(apocalypseGetElementData(source,"Rocket") == true)then
			NPC.MeMessage(player,getText(player,"SRhinoMission5"))
			toggleAllControls(player,false)
			triggerClientEvent(player,"createProgressBar",player,5)
			toggleControl(player, "vehicle_fire", false)
			toggleControl(player, "vehicle_secondary_fire", false)
			RocketTimer[player] = setTimer(function(player,veh)
				local item = 1
				if(SERVERBONUS.RHINO == true)then item = 2 end
				giveItem(player,143,item)
				triggerClientEvent(player, "showItemBar", player, {{143,item}})
				NPC.MeMessage(player,getText(player,"SRhinoMission4"))
				apocalypseSetElementData(veh,"Rocket",false)
				toggleAllControls(player,true)
				triggerClientEvent(player, "showItemBar", player, {{143,1}})
			end,5000,1,player,source)
		else
			NPC.MeMessage(player,getText(player,"SRhinoMission3"))
		end
	end)
	
	addEventHandler("onVehicleExit",RhinoMission.Vehicle[index],function(player)
		if(isTimer(RocketTimer[player]))then
			killTimer(RocketTimer[player])
		end
		toggleControl(player, "vehicle_fire", true)
		toggleControl(player, "vehicle_secondary_fire", true)
	end)

    addEventHandler("onVehicleExplode", veh, function()
        local player = getPlayerFromName(getElementData(source, "LastHit"))
        if isElement(player) then
            local rhinos_destroyed = getPlayerData("character_stats", "character_id", getCharacterID(player), "rhinos_destroyed")
            local newRhinos = rhinos_destroyed + 1
            dbExec(handler, "UPDATE character_stats SET rhinos_destroyed = ? WHERE character_id = ?", newRhinos, getCharacterID(player))
			local Level_Bonus_EXP = tonumber(apocalypseGetElementData(source,"level"))
			if(Level_Bonus_EXP > 100)then Level_Bonus_EXP = 100 end
			local xp, skillpoints = 500 + (Level__Bonus_EXP * 25), 5
			if(SERVERBONUS.RHINOS == true)then
				xp = xp * 2
				skillpoints = skillpoints * 2
			end
            giveEXP(player, xp)
            givePlayerSkillpoint(player, skillpoints)
            setAchievement(player,95)
            NPC.MeMessage(player, getText(player, "SRhinoMission1"))
			outputLog(getPlayerName(player).." hat einen Panzer zerstört und "..xp.." EXP und "..skillpoints.." Skillpunkte bekommen","Rhinos",getCharacterID(player))

            if DailyTasks.playerTasks[player][11] then
                DailyTasks.updateProgress(player,11,DailyTasks.playerTasks[player][11].progress + 1)
            end
            if WeeklyTasks.playerTasks[player][11] then
                WeeklyTasks.updateProgress(player,11,WeeklyTasks.playerTasks[player][11].progress + 1)
            end

            for _, v in ipairs(Achievements) do
                if newRhinos >= v[1] then
                    setAchievement(player, v[2])
                end
            end
        end
        setTimer(function(vehicle)
            destroyElement(vehicle)
        end, 15000, 1, source)
    end)
end

function RhinoMission.spawnAllRhinos()
    for i = 1, #RhinoMission.SpawnPosition do
        if not isElement(RhinoMission.Vehicle[i]) then
            createRhinoAtIndex(i)
        end
    end
end

function RhinoMission.createRhino()
    local maxAttempts = #RhinoMission.SpawnPosition
    local attempts = 0

    while attempts < maxAttempts do
        local rnd = math.random(1, #RhinoMission.SpawnPosition)
        if not isElement(RhinoMission.Vehicle[rnd]) then
            createRhinoAtIndex(rnd)
            return
        end
        attempts = attempts + 1
    end
end

RhinoMission.spawnAllRhinos()
setTimer(RhinoMission.createRhino, 300000, 0)