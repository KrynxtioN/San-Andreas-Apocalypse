function JobInformation.createWindow(id)
	JobInformation.text = JobInformation["Information"][apocalypseGetElementData(localPlayer,"language") or "EN"][id].name.."\n\n"..JobInformation["Information"][apocalypseGetElementData(localPlayer,"language") or "EN"][id].description
	addEventHandler("onClientRender",root,JobInformation.dxDraw)
	bindKey("space","down",JobInformation.closeWindow)
end
addEvent("JobInformation.createWindow",true)
addEventHandler("JobInformation.createWindow",root,JobInformation.createWindow)

function JobInformation.dxDraw()
	if(isWindowOpen())then
		local screenW, screenH = guiGetScreenSize()
		local backgroundColor = tocolor(0, 0, 0, 150)
		dxDrawRectangle(0, 0, screenW, screenH, backgroundColor)
		local textX = screenW / 2 - 300
		local textY = screenH / 2 - 100
		dxDrawText(JobInformation.text, textX, textY, textX + 600, textY + 200, tocolor(255, 255, 255, 255), 1.25, "default", "center", "center", true, true)
	end
end

function JobInformation.closeWindow()
	unbindKey("space","down",JobInformation.closeWindow)
	removeEventHandler("onClientRender",root,JobInformation.dxDraw)
end