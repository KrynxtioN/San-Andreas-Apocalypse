function DailyTasks.loadTasks(player)
	local characterID = getCharacterID(player)
	local result = dbPoll(dbQuery(handler,"SELECT * FROM dailytasks WHERE character_id = '"..characterID.."'"), -1)

	if (#result < 5) then
		local existingTaskIDs = {}
		for _, row in ipairs(result) do
			existingTaskIDs[tonumber(row.task)] = true
		end

		local availableTasks = {}
		for taskID, _ in pairs(DailyTasks["Tasks"]) do
			if not existingTaskIDs[taskID] then
				table.insert(availableTasks, taskID)
			end
		end

		local needed = 5 - #result
		for i = 1, needed do
			if #availableTasks == 0 then break end
			local randIndex = math.random(1, #availableTasks)
			local task = table.remove(availableTasks, randIndex)
			dbExec(handler,"INSERT INTO dailytasks (character_id,task,status,progress_data) VALUES ('"..characterID.."','"..task.."','0','0')")
		end

		result = dbPoll(dbQuery(handler,"SELECT * FROM dailytasks WHERE character_id = '"..characterID.."'"), -1)
	end

	if not DailyTasks.playerTasks[player] then
		DailyTasks.playerTasks[player] = {}
	end

	for i, v in ipairs(result) do
		local taskID = tonumber(v["task"])
		DailyTasks.playerTasks[player][taskID] = {
			id = taskID,
			text = DailyTasks["Tasks"][taskID][apocalypseGetElementData(player,"language") or "EN"].text,
			reward_exp = DailyTasks["Tasks"][taskID].reward_exp * apocalypseGetElementData(player,"level"),
			progress = tonumber(v["progress_data"]),
			needed_progress = DailyTasks["Tasks"][taskID].needed_progress,
			status = tonumber(v["status"]),
		}
	end

	DailyTasks.updateClient(player)
	triggerClientEvent(player, "DailyTasks.open", player)
end

function DailyTasks.updateClient(player)
	if(not(player))then player = client end
	triggerClientEvent(player,"DailyTasks.updateClient",player,DailyTasks.playerTasks[player])
end
addEvent("DailyTasks.updateClient",true)
addEventHandler("DailyTasks.updateClient",root,DailyTasks.updateClient)

function DailyTasks.updateProgress(player,task,new_data_progress)
	local task = tonumber(task)
	if(DailyTasks.playerTasks[player][task])then
		if(DailyTasks.playerTasks[player][task].status == 0)then
			DailyTasks.playerTasks[player][task].progress = new_data_progress
			dbExec(handler,"UPDATE dailytasks SET progress_data = '"..DailyTasks.playerTasks[player][task].progress.."' WHERE character_id = '"..getCharacterID(player).."' AND task = '"..task.."'")
			if(DailyTasks.playerTasks[player][task].progress >= DailyTasks.playerTasks[player][task].needed_progress)then
				DailyTasks.playerTasks[player][task].status = 1
				giveEXP(player,DailyTasks.playerTasks[player][task].reward_exp)
				dbExec(handler,"UPDATE dailytasks SET status = '1' WHERE character_id = '"..getCharacterID(player).."' AND task = '"..task.."'")
				outputLog(getPlayerName(player).." hat "..DailyTasks.playerTasks[player][task].reward_exp.." EXP durch eine Tagesaufgabe erhalten", "Daily Task", getCharacterID(player))
			end
			DailyTasks.updateClient(player)
		end
	end
end

function DailyTasks.deleteAllTasks()
	dbExec(handler,"DELETE FROM dailytasks")
end

function DailyTasks.giveNewTask(player)
	if(not(player))then player = client end
	local characterID = getCharacterID(player)
	if not DailyTasks.playerTasks[player] then DailyTasks.playerTasks[player] = {} end

	local money = tonumber(apocalypseGetElementData(player,"money"))
	if(money >= 500)then
		local ownedTasks = {}
		for taskID, _ in pairs(DailyTasks.playerTasks[player]) do
			ownedTasks[taskID] = true
		end

		local availableTasks = {}
		for taskID, _ in pairs(DailyTasks["Tasks"]) do
			if not ownedTasks[taskID] then
				table.insert(availableTasks, taskID)
			end
		end

		if #availableTasks == 0 then
			createInfobox(player,getText(player,"SDailyTasks1"))
			return false
		end

		local randIndex = math.random(1, #availableTasks)
		local newTaskID = table.remove(availableTasks, randIndex)

		dbExec(handler,"INSERT INTO dailytasks (character_id,task,status,progress_data) VALUES ('"..characterID.."','"..newTaskID.."','0','0')")

		DailyTasks.playerTasks[player][newTaskID] = {
			id = newTaskID,
			text = DailyTasks["Tasks"][newTaskID][apocalypseGetElementData(player,"language") or "EN"].text,
			reward_exp = DailyTasks["Tasks"][newTaskID].reward_exp,
			progress = 0,
			needed_progress = DailyTasks["Tasks"][newTaskID].needed_progress,
			status = 0,
		}

		DailyTasks.updateClient(player)
		apocalypseSetElementData(player,"money",money - 500)
		createInfobox(player,getText(player,"SDailyTasks2"):format(DailyTasks.playerTasks[player][newTaskID].text))
		return true
	else
		createInfobox(player,getText(player,"SDailyTasks3"))
	end
end
addEvent("DailyTasks.giveNewTask",true)
addEventHandler("DailyTasks.giveNewTask",root,DailyTasks.giveNewTask)