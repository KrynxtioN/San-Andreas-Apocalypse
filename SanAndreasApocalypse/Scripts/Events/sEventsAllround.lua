function Events.loadCollectibleDecoration()
	local model = 1935
	local r,g,b = 237, 95, 24
	for i,v in ipairs(Events["CollectibleDecorationPosition"])do
		Events.CollectibleDecoration[i] = createObject(model,v[1],v[2],v[3],v[4],v[5],v[6])
		Events.CollectibleDecorationMarker[i] = createMarker(v[1],v[2],v[3],"corona",0.5,r,g,b,100)
		apocalypseSetElementData(Events.CollectibleDecoration[i],"PumpkinID",i)
		Events.CollectibleDecorationTimer[i] = {}
	end
end

addEventHandler("onPlayerClick", root, function(button, state, clickedElement)
	if(button == "left" and state == "down" and clickedElement)then
		if(clickedElement)then
			if(apocalypseGetElementData(clickedElement,"PumpkinID"))then
				if(isElement(clickedElement) and getElementModel(clickedElement) == 1935)then
					local x, y, z = getElementPosition(source)
					if(getDistanceBetweenPoints3D(x, y, z, getElementPosition(clickedElement)) <= 5)then
						local player = source
						local currentTime = getRealTime().timestamp
						local objectID = apocalypseGetElementData(clickedElement,"PumpkinID")
						if(not(Events.CollectibleDecorationTimer[objectID][player]))then
							Events.CollectibleDecorationTimer[objectID][player] = 0
						end

						local playerTimer = Events.CollectibleDecorationTimer[objectID][player]
						if(playerTimer == 0 or currentTime - playerTimer >= 900)then
							giveHalloweenPumpkin(player,1)
							Events.CollectibleDecorationTimer[objectID][player] = currentTime
						end
					end
				end
			end
		end
	end
end)

if(HalloweenEvent == true)then
	Events.loadCollectibleDecoration()
end