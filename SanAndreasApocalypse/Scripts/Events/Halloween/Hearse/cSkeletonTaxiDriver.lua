addEvent("SkeletonTaxiDriver.reset",true)
addEventHandler("SkeletonTaxiDriver.reset",root,SkeletonTaxiDriver.reset)

addEventHandler("onClientClick",root,function(button,state,_,_,_,_,_,clickedElement)
    if not SkeletonTaxiDriver.Active then return end
    if button == "left" and state == "up" then
        for pedID,ped in pairs(SkeletonTaxiDriver.Ped) do
            if ped == clickedElement and isElement(ped) then
                SkeletonTaxiDriver.takePed(pedID)
                break
            end
        end
    end
end)

