                            )
                        end
                    end
                end
            end
        end

        local marker = SkeletonTaxiDriver.Marker[SkeletonTaxiDriver.lastID]
        if marker and isElement(marker) then
            local mx, my, mz = getElementPosition(marker)
            if getDistanceBetweenPoints3D(mx, my, mz, getElementPosition(localPlayer)) < 50 then
