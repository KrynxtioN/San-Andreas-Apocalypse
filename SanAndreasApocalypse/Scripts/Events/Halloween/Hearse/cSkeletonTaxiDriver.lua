    SkeletonTaxiDriver.MarkerBlip[rnd] = nil

    SkeletonTaxiDriver.lastID = rnd
    SkeletonTaxiDriver.lastDeliveryPoint = rndDelivery
    SkeletonTaxiDriver.HasPassenger = false
end

function SkeletonTaxiDriver.takePed(pedID)
    if not SkeletonTaxiDriver.Active or SkeletonTaxiDriver.HasPassenger then return end
    local ped = SkeletonTaxiDriver.Ped[pedID]
    if ped and isElement(ped) then
        local veh = getPedOccupiedVehicle(localPlayer)
        if veh then
            local x,y,z = getElementPosition(veh)

            destroyElement(ped)
            SkeletonTaxiDriver.Ped[pedID] = nil
            SkeletonTaxiDriver.HasPassenger = true

            if SkeletonTaxiDriver.Pickup[pedID] and isElement(SkeletonTaxiDriver.Pickup[pedID]) then
                destroyElement(SkeletonTaxiDriver.Pickup[pedID])
            end

            local pickup = createPickup(x,y,z+2,3,1318)
            attachElements(pickup, veh, 0,0,2)
            SkeletonTaxiDriver.Pickup[pedID] = pickup

            if SkeletonTaxiDriver.Blip[pedID] and isElement(SkeletonTaxiDriver.Blip[pedID]) then
                destroyElement(SkeletonTaxiDriver.Blip[pedID])
            end
            SkeletonTaxiDriver.Blip[pedID] = SkeletonTaxiDriver.createBlip(pickup)

            SkeletonTaxiDriver.PickupStartPos[pedID] = {x,y,z}

            local pos = SkeletonTaxiDriver.DeliveryPoint[SkeletonTaxiDriver.lastDeliveryPoint]
            local marker = createMarker(pos[1], pos[2], pos[3], "cylinder", 2, 255,140,0,150)
            SkeletonTaxiDriver.Marker[pedID] = marker

            SkeletonTaxiDriver.MarkerBlip[pedID] = SkeletonTaxiDriver.createBlip(marker)

            addEventHandler("onClientMarkerHit", marker, function(player)
                if player == localPlayer and SkeletonTaxiDriver.HasPassenger then
                    local veh = getPedOccupiedVehicle(localPlayer)
                    if veh then
                        local px,py,pz = getElementPosition(veh)
                        SkeletonTaxiDriver.TotalDistance = getDistanceBetweenPoints3D(
                            SkeletonTaxiDriver.PickupStartPos[pedID][1],
                            SkeletonTaxiDriver.PickupStartPos[pedID][2],
                            SkeletonTaxiDriver.PickupStartPos[pedID][3],
                            px,py,pz
                        )
                    end
                    triggerServerEvent("SkeletonTaxiDriver.Finished", localPlayer, math.floor(SkeletonTaxiDriver.TotalDistance/50))
                    createInfobox(getText("CSkeletonTaxiDriver1"):format(string.format("%.1f",SkeletonTaxiDriver.TotalDistance)))

                    if SkeletonTaxiDriver.Blip[pedID] and isElement(SkeletonTaxiDriver.Blip[pedID]) then
                        destroyElement(SkeletonTaxiDriver.Blip[pedID])
                        SkeletonTaxiDriver.Blip[pedID] = nil
                    end
                    if SkeletonTaxiDriver.MarkerBlip[pedID] and isElement(SkeletonTaxiDriver.MarkerBlip[pedID]) then
                        destroyElement(SkeletonTaxiDriver.MarkerBlip[pedID])
                        SkeletonTaxiDriver.MarkerBlip[pedID] = nil
                    end

                    SkeletonTaxiDriver.resetPedAndMarker(pedID)
                    SkeletonTaxiDriver.spawnPed()
                end
            end)
        end
    end
end

function SkeletonTaxiDriver.resetPedAndMarker(id)
    if isElement(SkeletonTaxiDriver.Marker[id]) then destroyElement(SkeletonTaxiDriver.Marker[id]) end
    if isElement(SkeletonTaxiDriver.Pickup[id]) then destroyElement(SkeletonTaxiDriver.Pickup[id]) end
    if SkeletonTaxiDriver.Blip[id] and isElement(SkeletonTaxiDriver.Blip[id]) then destroyElement(SkeletonTaxiDriver.Blip[id]) end
    if SkeletonTaxiDriver.MarkerBlip[id] and isElement(SkeletonTaxiDriver.MarkerBlip[id]) then destroyElement(SkeletonTaxiDriver.MarkerBlip[id]) end
    SkeletonTaxiDriver.Ped[id] = nil
    SkeletonTaxiDriver.Pickup[id] = nil
    SkeletonTaxiDriver.Marker[id] = nil
    SkeletonTaxiDriver.Blip[id] = nil
    SkeletonTaxiDriver.MarkerBlip[id] = nil
    SkeletonTaxiDriver.HasPassenger = false
    SkeletonTaxiDriver.DistanceToMarker = 0
    SkeletonTaxiDriver.PickupStartPos[id] = nil
end

function SkeletonTaxiDriver.reset()
    SkeletonTaxiDriver.Active = false
    SkeletonTaxiDriver.HasPassenger = false
    SkeletonTaxiDriver.DistanceToMarker = 0
    SkeletonTaxiDriver.TotalDistance = 0
    SkeletonTaxiDriver.PickupStartPos = {}

    for i, ped in pairs(SkeletonTaxiDriver.Ped) do if isElement(ped) then destroyElement(ped) end end
    for i, pickup in pairs(SkeletonTaxiDriver.Pickup) do if isElement(pickup) then destroyElement(pickup) end end
    for i, marker in pairs(SkeletonTaxiDriver.Marker) do if isElement(marker) then destroyElement(marker) end end
    for i, blip in pairs(SkeletonTaxiDriver.Blip) do if isElement(blip) then destroyElement(blip) end end
    for i, mblip in pairs(SkeletonTaxiDriver.MarkerBlip) do if isElement(mblip) then destroyElement(mblip) end end

    SkeletonTaxiDriver.Ped = {}
    SkeletonTaxiDriver.Pickup = {}
    SkeletonTaxiDriver.Marker = {}
    SkeletonTaxiDriver.Blip = {}
    SkeletonTaxiDriver.MarkerBlip = {}
    SkeletonTaxiDriver.lastID = 0
    SkeletonTaxiDriver.lastDeliveryPoint = 0
end

