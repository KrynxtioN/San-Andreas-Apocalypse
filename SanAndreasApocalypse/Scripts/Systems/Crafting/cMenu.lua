local screenW, screenH = guiGetScreenSize()
local panelWidth = 350
local craftingBoxSize = 80
local padding = 20
local panelX = (screenW - panelWidth - padding - (craftingBoxSize * 3)) / 2
local panelY = (screenH - panelHeight) / 2
local craftingX = panelX + panelWidth + padding
local craftingY = panelY

