local function getCurrentLanguage()
	return apocalypseGetElementData(localPlayer, "language") or "EN"
end

local function getItemDataByID(itemID)
	local lang = getCurrentLanguage()
	for _, item in ipairs(items[lang] or items["EN"]) do
		if item.id == itemID then
			return item
		end
	end
	return {
		id = itemID,
		name = tostring(itemID),
		image = "Files/Images/Inventory/" .. tostring(itemID) .. ".png"
	}
end

local function getRecipeByResultID(resultID)
	local lang = getCurrentLanguage()
	for _, recipe in ipairs(craftingRecipes[lang] or craftingRecipes["EN"]) do
		if recipe.result and recipe.result.id == resultID then
			return recipe
		end
	end
	return nil
end

local function selectOwnedRecipe(recipeUnlockID)
	local resultID = recipeResultMap[tonumber(recipeUnlockID)]
	if not resultID then return end

	local recipe = getRecipeByResultID(resultID)
	if not recipe then return end

	for i = 1, 9 do
		local ingredientID = recipe.ingredients[i] or 0
		if ingredientID ~= 0 then
			craftingGrid[i] = getItemDataByID(ingredientID)
		else
			craftingGrid[i] = nil
		end
	end

	updateCraftingPreview()
end

addEvent("Collectibles.updateData", true)
addEventHandler("Collectibles.updateData", root, function(data)
	if source ~= localPlayer then return end
	ownedRecipes = data or {}
	selectedRecipeIndex = nil
end)

function scrollItems(delta)
	scrollOffset = scrollOffset - delta
	local totalItems = #items[getCurrentLanguage()]
	local maxOffset = math.max(0, totalItems - visibleItems)
	if scrollOffset < 0 then scrollOffset = 0 end
	if scrollOffset > maxOffset then scrollOffset = maxOffset end
end

function craftingPanelScrollUp() scrollItems(1) end
function craftingPanelScrollDown() scrollItems(-1) end

function renderCraftingPanel()
	dxDrawRectangle(panelX, panelY, panelWidth, panelHeight, tocolor(50, 50, 50, 220))
	dxDrawText(getText("CCraftMenu2"), panelX, panelY - 30, panelX + panelWidth, panelY, tocolor(255, 255, 255), 1.5, "default-bold", "center", "top")

	for i = 1 + scrollOffset, math.min(#items[getCurrentLanguage()], visibleItems + scrollOffset) do
		local item = items[getCurrentLanguage()][i]
		local itemY = panelY + (i - 1 - scrollOffset) * itemHeight + 10
		local count = getCraftingItemCount(item.id) or "0"
		local backgroundColor = (selectedItemIndex == i) and tocolor(50, 200, 50, 200) or tocolor(60, 60, 60, 200)
		dxDrawRectangle(panelX + 10, itemY, panelWidth - 20, itemHeight - 5, backgroundColor)
		dxDrawText(item.name .. " (" .. count .. ")", panelX + 15, itemY, panelX + panelWidth - 20, itemY + itemHeight - 5, tocolor(255, 255, 255), 1, "default")
	end

	local totalItems = #items[getCurrentLanguage()]
	if(totalItems > visibleItems)then
		local scrollBarWidth = 10
		local scrollBarX = panelX + panelWidth - scrollBarWidth
		local scrollBarY = panelY + 10
		local scrollBarHeight = panelHeight - 20
		local thumbHeight = scrollBarHeight * visibleItems / totalItems
		if thumbHeight < 20 then thumbHeight = 20 end
		local thumbY = scrollBarY + (scrollOffset / (totalItems - visibleItems)) * (scrollBarHeight - thumbHeight)
		dxDrawRectangle(scrollBarX, scrollBarY, scrollBarWidth, scrollBarHeight, tocolor(100, 100, 100, 220))
		dxDrawRectangle(scrollBarX, thumbY, scrollBarWidth, thumbHeight, tocolor(150, 150, 150, 220))
	end

	dxDrawRectangle(craftingX, craftingY, craftingBoxSize * 3, craftingBoxSize * 3, tocolor(50, 50, 50, 220))
	dxDrawText(getText("CCraftMenu3"), craftingX, craftingY - 30, craftingX + craftingBoxSize * 3, craftingY, tocolor(255, 255, 255), 1.5, "default-bold", "center", "top")
	
	dxDrawRectangle(buttonStartX, buttonY, buttonWidth, buttonHeight, tocolor(80, 150, 80, 220))
	dxDrawText(getText("CCraftMenu4"), buttonStartX, buttonY, buttonStartX + buttonWidth, buttonY + buttonHeight, tocolor(255, 255, 255), 1.2, "default-bold", "center", "center")

	dxDrawRectangle(backButtonX, buttonY, buttonWidth, buttonHeight, tocolor(200, 50, 50, 220))
	dxDrawText(getText("CCraftMenu5"), backButtonX, buttonY, backButtonX + buttonWidth, buttonY + buttonHeight, tocolor(255, 255, 255), 1.2, "default-bold", "center", "center")

	for i = 0, 2 do
		for j = 0, 2 do
			local boxX = craftingX + i * craftingBoxSize
			local boxY = craftingY + j * craftingBoxSize
			local index = i + j * 3 + 1
			dxDrawRectangle(boxX, boxY, craftingBoxSize - 5, craftingBoxSize - 5, tocolor(70, 70, 70, 200))
			if craftingGrid[index] then
				dxDrawImage(boxX + 10, boxY + 10, craftingBoxSize - 20, craftingBoxSize - 20, craftingGrid[index].image)
			end
		end
	end

	if(craftedPreviewItem)then
		local previewBoxX = craftingX
		local previewBoxY = craftingY + craftingBoxSize * 3 + 30
		dxDrawRectangle(previewBoxX, previewBoxY + buttonHeight + 10, craftingBoxSize * 3, craftingBoxSize, tocolor(50, 50, 50, 220))
		dxDrawImage(previewBoxX + 10, previewBoxY + buttonHeight + 20, craftingBoxSize - 20, craftingBoxSize - 20, craftedPreviewItem.image)
	end

	dxDrawRectangle(recipePanelX, recipePanelY, recipePanelWidth, recipePanelHeight, tocolor(50, 50, 50, 220))
	dxDrawText(getText("CCraftMenu6"), recipePanelX, recipePanelY - 30, recipePanelX + recipePanelWidth, recipePanelY, tocolor(255, 255, 255), 1.5, "default-bold", "center", "top")

	if #ownedRecipes > 0 then
		for i, recipeData in ipairs(ownedRecipes) do
			local itemY = recipePanelY + (i - 1) * recipeItemHeight + 10
			if itemY + recipeItemHeight <= recipePanelY + recipePanelHeight then
				local backgroundColor = (selectedRecipeIndex == i) and tocolor(50, 200, 50, 200) or tocolor(60, 60, 60, 200)
				dxDrawRectangle(recipePanelX + 10, itemY, recipePanelWidth - 20, recipeItemHeight - 5, backgroundColor)
				dxDrawText(recipeData.name, recipePanelX + 15, itemY, recipePanelX + recipePanelWidth - 20, itemY + recipeItemHeight - 5, tocolor(255, 255, 255), 1, "default", "left", "center")
			end
		end
	else
		dxDrawText(getText("CCraftMenu7"), recipePanelX, recipePanelY, recipePanelX + recipePanelWidth, recipePanelY + recipePanelHeight, tocolor(200, 200, 200), 1, "default", "center", "center")
	end
end

function onMouseClickCrafting(button, state, absX, absY)
	if(button == "left" and state == "down")then
		if(absX > buttonStartX and absX < buttonStartX + buttonWidth and absY > buttonY and absY < buttonY + buttonHeight)then
			craftItem()
			return
		end

		if(absX > backButtonX and absX < backButtonX + buttonWidth and absY > buttonY and absY < buttonY + buttonHeight)then
			backFromCraftingMenu()
			removeEventHandler("onClientRender", root, renderCraftingPanel)
			removeEventHandler("onClientClick", root, onMouseClickCrafting)
			unbindKey("mouse_wheel_up", "down", craftingPanelScrollUp)
			unbindKey("mouse_wheel_down", "down", craftingPanelScrollDown)
			return
		end

		for i = 1 + scrollOffset, math.min(#items[getCurrentLanguage()], visibleItems + scrollOffset) do
			local item = items[getCurrentLanguage()][i]
			local itemY = panelY + (i - 1 - scrollOffset) * itemHeight + 10
			if absX > panelX + 10 and absX < panelX + panelWidth - 10 and absY > itemY and absY < itemY + itemHeight then
				selectedItem = item
				selectedItemIndex = i
				return
			end
		end

		for i = 1, #ownedRecipes do
			local itemY = recipePanelY + (i - 1) * recipeItemHeight + 10
			if absX > recipePanelX + 10 and absX < recipePanelX + recipePanelWidth - 10 and absY > itemY and absY < itemY + recipeItemHeight then
				selectedRecipeIndex = i
				selectOwnedRecipe(ownedRecipes[i].id)
				return
			end
		end

		for i = 0, 2 do
			for j = 0, 2 do
				local boxX = craftingX + i * craftingBoxSize
				local boxY = craftingY + j * craftingBoxSize
				local index = i + j * 3 + 1
				if absX > boxX and absX < boxX + craftingBoxSize - 5 and absY > boxY and absY < boxY + craftingBoxSize - 5 then
					if craftingGrid[index] then
						craftingGrid[index] = nil
					elseif selectedItem then
						craftingGrid[index] = selectedItem
					end
					updateCraftingPreview()
					return
				end
			end
		end
	end
end

function updateCraftingPreview()
	local inputItems = {}
	for i = 1, 9 do
		if craftingGrid[i] then
			table.insert(inputItems, craftingGrid[i].id)
		else
			table.insert(inputItems, 0)
		end
	end

	craftedPreviewItem = nil
	for _, recipe in ipairs(craftingRecipes[getCurrentLanguage()]) do
		if table.concat(recipe.ingredients) == table.concat(inputItems) then
			craftedPreviewItem = recipe.result
			return
		end
	end
end

function craftItem()
	if(craftedPreviewItem)then
		triggerServerEvent("Craftmenu.use", localPlayer, craftedPreviewItem.id)
	end
end

