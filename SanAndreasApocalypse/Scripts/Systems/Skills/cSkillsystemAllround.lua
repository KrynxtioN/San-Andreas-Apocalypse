local skillWindow = false
local skillID = nil
local progress = 0
local levelText = ""
local costText = ""
local description = ""
local buyButton = {x = 0, y = 0, w = 0, h = 0}
local closeBtn = {x = 0, y = 0, w = 0, h = 0}

local skillPickupLabels = {}

addEvent("Skillsystem.addPickupLabel", true)
addEventHandler("Skillsystem.addPickupLabel", root, function(pickup, labelSkillID)
	if isElement(pickup) and labelSkillID then
		skillPickupLabels[pickup] = tonumber(labelSkillID)
	end
end)

addEventHandler("onClientResourceStart", resourceRoot, function()
	triggerServerEvent("Skillsystem.requestPickupLabels", localPlayer)
	addEventHandler("onClientRender", root, Skillsystem.drawPickupLabels)
end)

function Skillsystem.drawPickupLabels()
	local px, py, pz = getElementPosition(localPlayer)
	local playerInterior = getElementInterior(localPlayer)
	local playerDimension = getElementDimension(localPlayer)
	local lang = apocalypseGetElementData(localPlayer, "language") or "EN"

	for pickup, labelSkillID in pairs(skillPickupLabels) do
		if not isElement(pickup) then
			skillPickupLabels[pickup] = nil
		else
			if getElementInterior(pickup) == playerInterior and getElementDimension(pickup) == playerDimension then
				local x, y, z = getElementPosition(pickup)
				local distance = getDistanceBetweenPoints3D(px, py, pz, x, y, z)

				if distance <= 25 then
					local sx, sy = getScreenFromWorldPosition(x, y, z + 1.05)

					if sx and sy then
						local skillName = "Skill"

						if Skillsystem["Skills"][lang] and Skillsystem["Skills"][lang][labelSkillID] then
							skillName = Skillsystem["Skills"][lang][labelSkillID][1]
						elseif Skillsystem["Skills"]["EN"] and Skillsystem["Skills"]["EN"][labelSkillID] then
							skillName = Skillsystem["Skills"]["EN"][labelSkillID][1]
						end

						dxDrawText(skillName, sx + 1, sy + 1, sx + 1, sy + 1, tocolor(0, 0, 0, 220), 1.1, "default-bold", "center", "center")
						dxDrawText(skillName, sx, sy, sx, sy, tocolor(255, 255, 255, 255), 1.1, "default-bold", "center", "center")
					end
				end
			end
		end
	end
end

function Skillsystem.createWindow(ID)
	if isWindowOpen() then
		skillWindow = true
		skillID = tonumber(ID)

		local lang = apocalypseGetElementData(localPlayer, "language") or "EN"
		description = Skillsystem["Skills"][lang][skillID][2]

		addEventHandler("onClientRender", root, Skillsystem.drawWindow)
		showCursor(true)

		triggerServerEvent("Skillsystem.getWindowData", localPlayer, localPlayer, skillID)
		addEventHandler("onClientClick", root, Skillsystem.click)
	end
end

addEvent("Skillsystem.createWindow", true)
addEventHandler("Skillsystem.createWindow", root, Skillsystem.createWindow)

function Skillsystem.closeWindow()
	if skillWindow then
		skillWindow = false
		removeEventHandler("onClientRender", root, Skillsystem.drawWindow)
		showCursor(false)

		skillID = nil
		progress = 0
		levelText = ""
		costText = ""
		description = ""

		removeEventHandler("onClientClick", root, Skillsystem.click)
	end
end

function Skillsystem.drawWindow()
	if not skillWindow or not skillID then return end

	local sx, sy = guiGetScreenSize()
	local w, h = 540, 340
	local x, y = (sx - w) / 2, (sy - h) / 2

	dxDrawRectangle(x, y, w, h, tocolor(20, 20, 20, 220), true)
	dxDrawRectangle(x, y, w, 36, tocolor(40, 40, 40, 240), true)

	local lang = apocalypseGetElementData(localPlayer, "language") or "EN"

	dxDrawText(getText("CSkillsystem1"):format(Skillsystem["Skills"][lang][skillID][1]), x + 12, y, x + w - 12, y + 36, tocolor(255, 255, 255, 255), 1.05, "default-bold", "left", "center", true, true, true)

	closeBtn.w, closeBtn.h = 26, 26
	closeBtn.x = x + w - closeBtn.w - 8
	closeBtn.y = y + 5

	local closeHover = isMouseInPosition(closeBtn.x, closeBtn.y, closeBtn.w, closeBtn.h)
	local closeColor = closeHover and tocolor(200, 60, 60, 230) or tocolor(160, 40, 40, 200)

	dxDrawRectangle(closeBtn.x, closeBtn.y, closeBtn.w, closeBtn.h, closeColor, true)
	dxDrawText("×", closeBtn.x, closeBtn.y, closeBtn.x + closeBtn.w, closeBtn.y + closeBtn.h, tocolor(255, 255, 255, 255), 1.3, "default-bold", "center", "center", true, true, true)

	dxDrawRectangle(x + 20, y + 58, w - 40, 28, tocolor(70, 70, 70, 200), true)
	dxDrawRectangle(x + 20, y + 58, math.max(4, (w - 40) * (progress / 100)), 28, tocolor(225,20,20, 220), true)

	dxDrawText(levelText, x + 20, y + 58, x + w - 20, y + 58 + 28, tocolor(255, 255, 255, 255), 1, "default-bold", "center", "center", true, true, true)
	dxDrawText(description, x + 22, y + 100, x + w - 22, y + 220, tocolor(230, 230, 230, 255), 1, "default", "left", "top", true, true, true)
	dxDrawText(costText, x + 22, y + 228, x + w - 22, y + 250, tocolor(200, 200, 200, 255), 1, "default-bold", "left", "top", true, true, true)

	buyButton.x, buyButton.y, buyButton.w, buyButton.h = x + 20, y + h - 52, w - 40, 36

	local hoverBuy = isMouseInPosition(buyButton.x, buyButton.y, buyButton.w, buyButton.h)
	local color = hoverBuy and tocolor(120, 180, 120, 255) or tocolor(90, 140, 90, 255)

	dxDrawRectangle(buyButton.x, buyButton.y, buyButton.w, buyButton.h, color, true)
	dxDrawText(getText("CSkillsystem3"), buyButton.x, buyButton.y, buyButton.x + buyButton.w, buyButton.y + buyButton.h, tocolor(255, 255, 255, 255), 1.05, "default-bold", "center", "center", true, true, true)
end

function Skillsystem.click(btn, state)
	if skillWindow and btn == "left" and state == "up" then
		if isMouseInPosition(closeBtn.x, closeBtn.y, closeBtn.w, closeBtn.h) then
			Skillsystem.closeWindow()
			return
		end

		if isMouseInPosition(buyButton.x, buyButton.y, buyButton.w, buyButton.h) then
			if skillID then
				triggerServerEvent("Skillsystem.buyUpgrade", localPlayer, skillID)
			end
		end
	end
end

addEvent("Skillsystem.updateWindowData", true)
addEventHandler("Skillsystem.updateWindowData", root, function(level, cost, max_level)
	if tonumber(level) >= tonumber(max_level) then
		progress = 100
		levelText = getText("CSkillsystem4")
		costText = ""
	else
		progress = (level / max_level) * 100
		levelText = getText("CSkillsystem6"):format(level, max_level)
		costText = getText("CSkillsystem2"):format(cost)
	end
end)

addEvent("Skillsystem.createGate", true)
addEventHandler("Skillsystem.createGate", root, function()
	if not isElement(Skillsystem.Gate) then
		Skillsystem.Gate = createObject(13028, 720.01879882812, -462.49310302734, 16.878099441528, 0, 0, 90)
	end
end)

addEvent("Skillsystem.destroyGate", true)
addEventHandler("Skillsystem.destroyGate", root, function()
	if isElement(Skillsystem.Gate) then
		destroyElement(Skillsystem.Gate)
	end
end)

addEventHandler("onClientPlayerWasted", root, function()
	if localPlayer == source then
		Skillsystem.closeWindow()
	end
end)