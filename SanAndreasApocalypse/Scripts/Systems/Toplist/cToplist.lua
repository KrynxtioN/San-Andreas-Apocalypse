addEvent("Toplist.setData",true)
addEventHandler("Toplist.setData",root,function(currentTop, data, playerRank, playerValue, playerName)
	if(#currentTop >= 1)then
		local text = ""
		for i = 1,#currentTop do
			if(data == "playtime")then
				currentTop[i][2] = formatMinutes(currentTop[i][2])
			end
			text = text.." \n"..i..". "..currentTop[i][1].." ("..currentTop[i][2]..")"
		end
		if(tonumber(playerRank) > 10)then
			guiSetText(GUIEditor.label[1],text.."\n\n"..playerRank..". "..playerName.." ("..playerValue..")")
		else
			guiSetText(GUIEditor.label[1],text)
		end
	end
end)

