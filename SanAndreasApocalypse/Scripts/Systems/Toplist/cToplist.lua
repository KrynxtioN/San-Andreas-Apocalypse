function Toplist.openWindow()
	if(isWindowOpen())then
        GUIEditor.window[1] = guiCreateWindow(583, 385, 550, 315, getText("CToplist1"), false)
		setWindowData()
		guiCreateCloseButton()

        GUIEditor.tabpanel[1] = guiCreateTabPanel(10, 29, 530, 276, false, GUIEditor.window[1])

        GUIEditor.tab[1] = guiCreateTab(getText("CToplist5"), GUIEditor.tabpanel[1])

        GUIEditor.gridlist[1] = guiCreateGridList(8, 10, 227, 232, false, GUIEditor.tab[1])
        category = guiGridListAddColumn(GUIEditor.gridlist[1], "", 0.9)
        GUIEditor.label[1] = guiCreateLabel(245, 10, 275, 232, getText("CToplist2"), false, GUIEditor.tab[1])
        guiLabelSetHorizontalAlign(GUIEditor.label[1], "center", true)
        guiLabelSetVerticalAlign(GUIEditor.label[1], "center")

        GUIEditor.tab[2] = guiCreateTab(getText("CToplist4"), GUIEditor.tabpanel[1])    
		
        GUIEditor.gridlist[2] = guiCreateGridList(8, 10, 227, 232, false, GUIEditor.tab[2])
        statistics = guiGridListAddColumn(GUIEditor.gridlist[2], "", 0.9)
        GUIEditor.label[2] = guiCreateLabel(245, 10, 275, 232, getText("CToplist2"), false, GUIEditor.tab[2])
        guiLabelSetHorizontalAlign(GUIEditor.label[2], "center", true)
        guiLabelSetVerticalAlign(GUIEditor.label[2], "center")
		
        GUIEditor.tab[3] = guiCreateTab(getText("CToplist6"), GUIEditor.tabpanel[1])    
		
        GUIEditor.gridlist[3] = guiCreateGridList(8, 10, 227, 232, false, GUIEditor.tab[3])
        records = guiGridListAddColumn(GUIEditor.gridlist[3], "", 0.9)
        GUIEditor.label[3] = guiCreateLabel(245, 10, 275, 232, getText("CToplist2"), false, GUIEditor.tab[3])
        guiLabelSetHorizontalAlign(GUIEditor.label[3], "center", true)
        guiLabelSetVerticalAlign(GUIEditor.label[3], "center")
		
        GUIEditor.tab[4] = guiCreateTab(getText("CToplist7"), GUIEditor.tabpanel[1])    
		
        GUIEditor.gridlist[4] = guiCreateGridList(8, 10, 227, 232, false, GUIEditor.tab[4])
        records = guiGridListAddColumn(GUIEditor.gridlist[4], "", 0.9)
        GUIEditor.label[4] = guiCreateLabel(245, 10, 275, 232, getText("CToplist2"), false, GUIEditor.tab[4])
        guiLabelSetHorizontalAlign(GUIEditor.label[4], "center", true)
        guiLabelSetVerticalAlign(GUIEditor.label[4], "center")

		for _,v in pairs(Toplist["Category"][apocalypseGetElementData(localPlayer,"language") or "EN"])do
			local row = guiGridListAddRow(GUIEditor.gridlist[1])
			guiGridListSetItemText(GUIEditor.gridlist[1],row,category,v,false,false)
		end
		
		for _,v in pairs(Toplist["Statistics"][apocalypseGetElementData(localPlayer,"language") or "EN"])do
			local row = guiGridListAddRow(GUIEditor.gridlist[2])
			guiGridListSetItemText(GUIEditor.gridlist[2],row,category,v,false,false)
		end
		
		for _,v in pairs(Toplist["Records"][apocalypseGetElementData(localPlayer,"language") or "EN"])do
			local row = guiGridListAddRow(GUIEditor.gridlist[3])
			guiGridListSetItemText(GUIEditor.gridlist[3],row,category,v,false,false)
		end
		
		for _,v in pairs(Toplist["Halloween"][apocalypseGetElementData(localPlayer,"language") or "EN"])do
			local row = guiGridListAddRow(GUIEditor.gridlist[4])
			guiGridListSetItemText(GUIEditor.gridlist[4],row,category,v,false,false)
		end
		
		addEventHandler("onClientGUIClick",GUIEditor.gridlist[1],function()
			local clicked = guiGridListGetItemText(GUIEditor.gridlist[1],guiGridListGetSelectedItem(GUIEditor.gridlist[1]),1)
			if(clicked ~= "")then
				triggerServerEvent("Toplist.getData",localPlayer,Toplist["DataName"][clicked])
			end
		end,false)
		
		addEventHandler("onClientGUIClick",GUIEditor.gridlist[2],function()
			local clicked = guiGridListGetItemText(GUIEditor.gridlist[2],guiGridListGetSelectedItem(GUIEditor.gridlist[2]),1)
			if(clicked ~= "")then
				triggerServerEvent("Toplist.getStats",localPlayer,Toplist["DataName"][clicked],2)
			end
		end,false)
		
		addEventHandler("onClientGUIClick",GUIEditor.gridlist[3],function()
			local clicked = guiGridListGetItemText(GUIEditor.gridlist[3],guiGridListGetSelectedItem(GUIEditor.gridlist[3]),1)
			if(clicked ~= "")then
				triggerServerEvent("Toplist.getRecords",localPlayer,Toplist["DataName"][clicked])
			end
		end,false)
		
		addEventHandler("onClientGUIClick",GUIEditor.gridlist[4],function()
			local clicked = guiGridListGetItemText(GUIEditor.gridlist[4],guiGridListGetSelectedItem(GUIEditor.gridlist[4]),1)
			if(clicked ~= "")then
				triggerServerEvent("Toplist.getStats",localPlayer,Toplist["DataName"][clicked],4)
			end
		end,false)
	end
end
