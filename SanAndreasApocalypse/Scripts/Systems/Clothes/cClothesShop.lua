function ClothesShop.createWindow(Type)
	if(isWindowOpen())then
		setWindowData("no")
		HUD.Visible = false
		setPlayerHudComponentVisible("radar",false)
		toggleMovingBlackBars()
		toggleAllControls(false)
		ClothesShop.selected = 1
		ClothesShop.selectedType = Type
		bindKey("arrow_l","down",ClothesShop.leftKey)
		bindKey("arrow_r","down",ClothesShop.rightKey)
		bindKey("enter","down",ClothesShop.buy)
		bindKey("backspace","down",ClothesShop.close)
		
		local tbl = ClothesShop["Data"][ClothesShop.selectedType]
		ClothesShop.Ped = createPed(0,tbl.ped[1],tbl.ped[2],tbl.ped[3],0)
		for i = 0, 17 do
            removePedClothes(ClothesShop.Ped, i)
        end
		setCameraMatrix(tbl.matrix[1],tbl.matrix[2],tbl.matrix[3],tbl.matrix[4],tbl.matrix[5],tbl.matrix[6],tbl.matrix[7],tbl.matrix[8])

		setElementInterior(ClothesShop.Ped,tbl.int)
		setElementInterior(localPlayer,tbl.int)
		addEventHandler("onClientRender",root,ClothesShop.render)
	end
end

function ClothesShop.render()
	if(isElement(ClothesShop.Ped))then
		local rot = getPedRotation(ClothesShop.Ped)
		setPedRotation(ClothesShop.Ped,rot+1)

		local screenW, screenH = guiGetScreenSize()
		local current = ClothesShop.selected
		local total = #ClothesShop[ClothesShop.selectedType]
		local name = ClothesShop[ClothesShop.selectedType][current][1]
		local text = string.format("%s (%d/%d)", name, current, total)
		
		if(ClothesShop.selectedType == "Haare")then item = 53 amount = 25 end
		if(ClothesShop.selectedType == "Tattoos")then item = 48 amount = 25 end
		if(ClothesShop.selectedType == "Shirts")then item = 32 amount = 25 end
		if(ClothesShop.selectedType == "Hosen")then item = 32 amount = 25 end
		if(ClothesShop.selectedType == "Schuhe")then item = 32 amount = 25 end
		if(ClothesShop.selectedType == "Kopfbedeckungen")then item = 32 amount = 25 end
		if(ClothesShop.selectedType == "Ketten")then item = 87 amount = 25 end
		if(ClothesShop.selectedType == "Uhren")then item = 88 amount = 25 end
		if(ClothesShop.selectedType == "Brillen")then item = 89 amount = 25 end

		dxDrawText(text, 0, 20, screenW, 60, tocolor(255,255,255,255), 1.5, "default-bold", "center", "top",true,true,true)
		dxDrawText(getText("CClothesShop1"):format(amount,ItemInfos["items"][apocalypseGetElementData(localPlayer,"language") or "EN"][item]), 0, 60, screenW, 100, tocolor(200,200,200,255), 1.1, "default", "center", "top",true,true,true)
	end
end

function ClothesShop.leftKey()
	if(ClothesShop.selected > 1)then
		ClothesShop.selected = ClothesShop.selected - 1
		local tbl = ClothesShop[ClothesShop.selectedType][ClothesShop.selected]
		for i = 0, 17 do
            removePedClothes(ClothesShop.Ped, i)
        end
		addPedClothes(ClothesShop.Ped,tbl[1],tbl[2],tbl[3])
	end
end

function ClothesShop.rightKey()
	if(ClothesShop.selected < #ClothesShop[ClothesShop.selectedType])then
		ClothesShop.selected = ClothesShop.selected + 1
		local tbl = ClothesShop[ClothesShop.selectedType][ClothesShop.selected]
		for i = 0, 17 do
            removePedClothes(ClothesShop.Ped, i)
        end
		addPedClothes(ClothesShop.Ped,tbl[1],tbl[2],tbl[3])
	end
end

function ClothesShop.buy()
	local tbl = ClothesShop[ClothesShop.selectedType][ClothesShop.selected]
	triggerServerEvent("ClothesShop.buy",localPlayer,tbl[1],tbl[2],tbl[3],ClothesShop.selectedType)
end

function ClothesShop.close()
	if(isElement(ClothesShop.Ped))then destroyElement(ClothesShop.Ped)end
	removeEventHandler("onClientRender",root,ClothesShop.render)
	setCameraTarget(localPlayer)
	closeWindow()
